        'development_per_class',10,'set_per_class',60,'evidence_per_class',40, ...
        'risk_per_class',30,'test_per_class',50,'stress_count',100, ...
        'seed_development',510000000,'seed_set',520000000, ...
        'seed_evidence',530000000,'seed_risk',540000000, ...
        'seed_test',550000000,'seed_library_out',560000000, ...
        'seed_parameter_out',570000000,'seed_snr_shift',580000000, ...
        'source_commit','5217ee8edf9b8a814d26690b873e28fd2d82e218', ...
        'use_parallel',false,'worker_count',0, ...
        'output_root',fullfile(base.root_dir,'results','data','stage7a_2',mode), ...
        'figure_root',fullfile(base.root_dir,'results','figures','stage7a_2'), ...
        'log_root',fullfile(base.root_dir,'results','logs','stage7a_2'));
    if strcmp(mode,'smoke')
        cfg.development_per_class=2;cfg.set_per_class=4;cfg.evidence_per_class=4;
        cfg.risk_per_class=4;cfg.test_per_class=2;cfg.stress_count=4;
        cfg.stage7a.evidence_calibration.minimum_reference_count=2;
    end
end
