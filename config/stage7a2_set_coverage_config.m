    if nargin<2||isempty(mode),mode='formal';end
    mode=lower(char(mode));assert(ismember(mode,{'smoke','formal'}),'stage7a2:Mode','Invalid mode.');
    sc=stage7a_profile_search_config(base,'formal');
    cfg=struct('mode',mode,'stage7a',sc,'alpha',0.05,'curve_alpha',[0.05 0.10 0.20], ...
        'risk_target',0.05,'risk_delta',0.05,'snr_db',20,'shift_snr_db',10, ...
        'main_bounds',[0.98 1.02],'load_bounds',[1 1], ...
