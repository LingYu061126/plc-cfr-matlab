        'src/stage4a7_2_r1_apply_profile_candidate_set.m','src/stage4a7_2_r1_method_selection.m', ...
        'src/stage4a7_2_r1_build_coverage_audit.m', ...
        'src/stage4a7_2_r1_nonunique_metrics.m','src/stage4a7_2_r1_topk_scaling_audit.m', ...
        'experiments/exp_stage4a7_2_r1_data_driven_closure.m'};
    payload=repmat(struct('relative_path','','content',''),1,numel(rel));
    for k=1:numel(rel)
        p=fullfile(root,rel{k});if ~exist(p,'file'),error('stage4a7_2_r1:MissingHashDependency','Missing %s.',rel{k});end
        payload(k)=struct('relative_path',rel{k},'content',fileread(p));
    end
    hash=stage4a4_scientific_config_hash(payload);
end
