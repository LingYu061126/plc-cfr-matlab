function [out, cluster_ids] = cluster_labels(labels)
    out = repmat(labels(1),0,1); cluster_ids = {};
    keys = cell(1,numel(labels));
    for k=1:numel(labels)
        keys{k}=getfield_default(labels(k),'noiseless_cfr_hash','');
        if isempty(keys{k}), keys{k}=getfield_default(labels(k),'parameter_vector_hash',''); end
        if isempty(keys{k}), keys{k}=getfield_default(labels(k),'physical_scenario_id',labels(k).sample_id); end
    end
    [u,ia] = unique(keys,'stable'); %#ok<ASGLU>
    out = labels(ia); cluster_ids = keys(ia);
end

function ids = split_ids(s)
    if isstring(s), s=char(s); end
    if isempty(s), ids={}; elseif iscell(s), ids=s; else, ids=strsplit(char(s),','); end
    ids = ids(~cellfun(@isempty,ids));
end
function tf = same_set(a,b),tf=numel(a)==numel(b)&&all(ismember(a,b))&&all(ismember(b,a));end
function n = count_unique_field(s, f)
    x = cell(1,numel(s)); for k=1:numel(s), x{k}=getfield_default(s(k),f,''); end
    x=x(~cellfun(@isempty,x)); if isempty(x),n=0;else,n=numel(unique(x));end
end
function [p,l,h] = rate(a,b)
    if b==0, p=NaN;l=NaN;h=NaN; return; end
    p=a/b; ci=stage4a6_3_wilson_interval(a,b); l=ci(1);h=ci(2);
end
function v=getfield_default(s,n,d),if isstruct(s)&&isfield(s,n),v=s.(n);else,v=d;end,end
