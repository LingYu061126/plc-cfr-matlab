function test_stage7a4_result_integrity(root,mode)
%TEST_STAGE7A4_RESULT_INTEGRITY Check frozen splits, counts and source hash.
    if nargin<1||isempty(root),root=fileparts(fileparts(mfilename('fullpath')));end
    if nargin<2||isempty(mode),mode='formal';end
    addpath(fullfile(root,'src'),fullfile(root,'config'));
    base=default_config(root);cfg=stage7a4_mirror_observation_config(base,mode);
    out=cfg.output_dir;
    files={'stage7a4_exploration.csv','stage7a4_error_scales.csv', ...
        'stage7a4_selection.csv','stage7a4_topologies.csv','stage7a4_port_catalog.csv', ...
        'stage7a4_scheme_catalog.csv','stage7a4_calibration.csv', ...
        'stage7a4_information_distance.csv','stage7a4_samples.csv', ...
        'stage7a4_summary.csv','stage7a4_positive_controls.csv', ...
        'stage7a4_control_decisions.csv','stage7a4_nominal_spectra.csv', ...
        'stage7a4_node_loading_effect.csv', ...
        'stage7a4_metadata.csv','stage7a4_source_inventory.csv', ...
        'stage7a4_artifact_manifest.csv', ...
        'stage7a4_config_snapshot.mat','stage7a4_exploration_snapshot.mat'};
    for k=1:numel(files)
        assert(exist(fullfile(out,files{k}),'file')==2, ...
            'Missing Stage 7A.4 artifact %s.',files{k});
    end
    topology=readtable(fullfile(out,'stage7a4_topologies.csv'),'TextType','string');
    assert(height(topology)==4&&nnz(topology.in_original_library)==3&& ...
        ~topology.in_original_library(topology.candidate_id=="MIRROR_M3")&& ...
        contains(topology.signature(topology.candidate_id=="MIRROR_M3"), ...
            "B=3,15,1,50;"));
    selection=readtable(fullfile(out,'stage7a4_selection.csv'),'TextType','string');
    assert(height(selection)==1&&selection.selected_B_termination_ohm==200&& ...
        selection.selected_C_node_index==3&& ...
        selection.A1_fine_interval=="none", ...
        'D/E selection differs from the archived frozen selection.');
    info=readtable(fullfile(out,'stage7a4_information_distance.csv'),'TextType','string');
    base_h=info(info.variant=="main" & info.scheme=="A0_H50",:);
    base_z=info(info.variant=="main" & info.scheme=="A0_Zin50",:);
    assert(height(base_h)==1&&height(base_z)==1&& ...
        base_h.min_profile_joint_distance<1e-12&& ...
        base_z.min_profile_joint_distance>=cfg.separation_threshold, ...
        'The recorded mirror overlap or input-impedance separation changed.');
    samples=readtable(fullfile(out,'stage7a4_samples.csv'),'TextType','string');
    schemes=unique(samples.scheme);n20=cfg.n_T_per_topology;
    for j=1:numel(schemes)
        pair=samples(samples.scenario=="T20" & samples.scheme==schemes(j) & ...
            samples.library=="diagnostic_pair",:);
        original=samples(samples.scenario=="T20" & samples.scheme==schemes(j) & ...
            samples.library=="original_three",:);
        assert(height(pair)==2*n20&&height(original)==4*n20&& ...
            nnz(original.truth_id=="MIRROR_M3")==n20 && ...
            all(original.truth_in_library(original.truth_id=="MIRROR_M3")==0), ...
            'T20 pair or original-library denominator is incorrect.');
    end
    assert(all(ismember(samples.decision_state, ...
        ["UNIQUE_CONFIDENT","MULTIPLE_AMBIGUOUS","LOW_CONFIDENCE","REJECTED"])), ...
        'Unexpected four-state decision code.');
    assert(~any(samples.correct_unique & samples.false_unique), ...
        'A decision cannot be both correct and false unique.');
    controls=readtable(fullfile(out,'stage7a4_positive_controls.csv'), ...
        'Delimiter',',','ReadVariableNames',true,'TextType','string');
    old=controls(controls.scheme=="A0_H50" & controls.control_pair=="T3_T5",:);
    repeated=controls(controls.scheme=="B_H50_repeat" & controls.control_pair=="T3_T5",:);
    assert(height(old)==1&&height(repeated)==1&& ...
        old.still_overlap_below_three_sigma&&repeated.still_overlap_below_three_sigma, ...
        'Original equivalent control was spuriously separated by repetition.');
    control_decisions=readtable(fullfile(out,'stage7a4_control_decisions.csv'), ...
        'Delimiter',',','ReadVariableNames',true,'TextType','string');
    old_decisions=control_decisions( ...
        ismember(control_decisions.scheme,["A0_H50","B_H50_repeat"]) & ...
        ismember(control_decisions.truth_id,["T3","T5"]),:);
    assert(height(old_decisions)==4&&all(old_decisions.correct_unique_k==0), ...
        'The uninformative original CFR views forced a unique positive control.');
    manifest=readtable(fullfile(out,'stage7a4_source_inventory.csv'),'TextType','string');
    for k=1:height(manifest)
        path=fullfile(root,strrep(char(manifest.relative_path(k)),'/',filesep));
        assert(exist(path,'file')==2,'Missing inventoried Stage 7A.4 source.');
        d=dir(path);assert(d.bytes==manifest.size_bytes(k));
        assert(strcmp(stage4a7_2_r2_sha256_file(path),char(manifest.sha256(k))), ...
            'Stage 7A.4 source SHA-256 mismatch.');
    end
    artifacts=readtable(fullfile(out,'stage7a4_artifact_manifest.csv'),'TextType','string');
    assert(height(artifacts)>=numel(files)-1, ...
        'Stage 7A.4 artifact manifest omits expected result files.');
    for k=1:height(artifacts)
        path=fullfile(root,strrep(char(artifacts.relative_path(k)),'/',filesep));
        assert(exist(path,'file')==2,'Missing inventoried Stage 7A.4 result.');
        d=dir(path);assert(d.bytes==artifacts.size_bytes(k));
        assert(strcmp(stage4a7_2_r2_sha256_file(path),char(artifacts.sha256(k))), ...
            'Stage 7A.4 result SHA-256 mismatch.');
    end
    fprintf('PASS test_stage7a4_result_integrity(%s): %d decisions, %d schemes\n', ...
        mode,height(samples),numel(schemes));
end
