function test_stage7a12_result_integrity(root,mode,run_id)
%TEST_STAGE7A12_RESULT_INTEGRITY Recount every result group from sample CSV.
    if nargin<1||isempty(root),root=fileparts(fileparts(mfilename('fullpath')));end
    if nargin<2||isempty(mode),mode='smoke';end
    if nargin<3||isempty(run_id),run_id='smoke1';end
    folder=fullfile(root,'results','data','stage7a_12',mode,run_id);
    s=readtable(fullfile(folder,'samples.csv'),'Delimiter',',', ...
        'TextType','string');
    a=readtable(fullfile(folder,'summary.csv'),'Delimiter',',', ...
        'TextType','string');
    ci=readtable(fullfile(folder,'ci_estimation.csv'),'Delimiter',',', ...
        'TextType','string');
    catalog=readtable(fullfile(folder,'graph_catalog.csv'),'Delimiter',',', ...
        'TextType','string');
    snapshot=load(fullfile(folder,'config_snapshot.mat'),'cfg');
    assert(isempty(intersect(snapshot.cfg.dev_ids, ...
        snapshot.cfg.test_ids)), ...
        'stage7a12:StructureLeakage', ...
        'Development and final graph structures overlap.');
    assert(all(catalog.searchable(ismember(catalog.graph_id, ...
        ["OUT10","OUT70","MID30","MID50"]))==0), ...
        'stage7a12:SearchSpaceIdentity', ...
        'Held-out grammar-out graph entered the search pool.');
    assert(height(s)==height(ci)*6,'stage7a12:SampleCount', ...
        'Sample and CI row counts differ.');
    assert(numel(unique(s.sample_id))==height(ci)/3, ...
        'stage7a12:UniqueSampleCount','Unique sample count differs.');
    generated=ismember(s.method,["B_ideal_ci","C_estimated_ci", ...
        "D_count_matched"]);
    assert(all(s.candidate_count(generated)<=3) && ...
        all(s.candidate_set_size<=s.candidate_count), ...
        'stage7a12:CandidateBudget', ...
        'Candidate budget or set subset failed.');
    assert(all(~s.correct_unique | s.truth_generated), ...
        'stage7a12:MissingTruthCountedAsSuccess', ...
        'Missing truth counted as successful confirmation.');
    assert(all(~s.correct_unique | s.decision_state=="UNIQUE_CONFIDENT"));
    assert(all(isnan(s.min_wrong_branch_edges(s.candidate_count==0))) && ...
        all(s.min_wrong_branch_edges(s.candidate_count>0)>=0) && ...
        all(s.min_wrong_branch_edges(s.truth_generated==1)==0), ...
        'stage7a12:StructureAudit','Structural audit contradicts selected graph.');
    assert(all(s.max_recovered_hidden_junctions<= ...
        s.truth_hidden_junction_count), ...
        'stage7a12:HiddenNodeAudit','Recovered hidden junction count exceeds truth.');
    for j=1:height(a)
        r=a(j,:);mask=s.condition==r.condition & ...
            s.method==r.method & s.truth_id==r.truth_id;
        x=s(mask,:);
        assert(height(x)==r.n && ...
            nnz(x.truth_generated)==r.generated_truth_k && ...
            nnz(x.correct_unique)==r.correct_unique_k && ...
            nnz(x.false_unique)==r.false_unique_k && ...
            nnz(x.truth_in_set)==r.truth_in_set_k && ...
            nnz(x.candidate_set_size>0)==r.nonempty_set_k && ...
            nnz(x.decision_state=="UNIQUE_CONFIDENT")==r.unique_k && ...
            nnz(x.decision_state=="MULTIPLE_AMBIGUOUS")==r.ambiguous_k && ...
            nnz(x.decision_state=="LOW_CONFIDENCE")==r.low_confidence_k && ...
            nnz(x.decision_state=="REJECTED")==r.rejected_k, ...
            'stage7a12:SummaryMismatch', ...
            'Summary row does not match samples.');
    end
    fprintf('PASS test_stage7a12_result_integrity: %d samples, %d groups\n', ...
        height(s),height(a));
end
