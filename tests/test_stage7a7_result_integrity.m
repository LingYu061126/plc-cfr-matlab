function test_stage7a7_result_integrity(root,mode,condition)
%TEST_STAGE7A7_RESULT_INTEGRITY Recompute decision/candidate CSV invariants.
    if nargin<1||isempty(root),root=fileparts(fileparts(mfilename('fullpath')));end
    if nargin<2||isempty(mode),mode='smoke';end
    if nargin<3||isempty(condition),condition='nominal';end
    addpath(fullfile(root,'src'),fullfile(root,'config'));
    d=fullfile(root,'results','data','stage7a_7',mode,condition);
    S=readtable(fullfile(d,'samples.csv'));
    C=readtable(fullfile(d,'candidate_audit.csv'));
    Q=readtable(fullfile(d,'summary.csv'));
    T=readtable(fullfile(d,'topology_summary.csv'));
    I=readtable(fullfile(d,'topology_inventory.csv'));
    K=readtable(fullfile(d,'calibration.csv'));
    M=readtable(fullfile(d,'metadata.csv'));
    assert(height(I)==39&&sum(I.in_new_pool)==37&& ...
        numel(unique(string(I.signature)))==39, ...
        'stage7a7:Inventory','Invalid topology inventory.');
    assert(height(S)==M.test_observations(1)*height(K), ...
        'stage7a7:DecisionCount','Unexpected decision count.');
    assert(all(S.correct_unique+S.false_unique<=1)&& ...
        all(S.correct_unique+S.false_unique<= ...
        strcmp(string(S.state),'UNIQUE_CONFIDENT')), ...
        'stage7a7:UniqueSemantics','Unique-output flags disagree with state.');
    assert(all(S.truth_in_set<=S.active), ...
        'stage7a7:TruthSet','Truth entered set without being scored.');
    assert(all(S.generated_by_edit<=S.active)&& ...
        all(S.added_by_completion<=S.active)&& ...
        all(S.generated_by_edit+S.added_by_completion<=1), ...
        'stage7a7:Generation','Generation/completion labels overlap.');
    full=strcmp(string(S.flow),'C37');
    assert(all(S.candidate_count(full)==37)&& ...
        all(S.pool_exhausted(full))&& ...
        ~any(S.search_truncated(full))&& ...
        all(S.unvisited_count(full)==0), ...
        'stage7a7:Completion','Full-pool completion is not exhaustive.');
    limited=strcmp(string(S.flow),'C5')|strcmp(string(S.flow),'C12');
    assert(all(S.search_truncated(limited))&& ...
        all(S.candidate_count(limited)<=S.budget(limited))&& ...
        all(S.unvisited_count(limited)>0), ...
        'stage7a7:Budget','Limited search escaped its safety gate.');
    keyS=join_key(S);keyC=join_key(C);
    [keyU,~,g]=unique(keyC);
    nC=accumarray(g,1);rank1=accumarray(g,C.rank==1);
    [tf,loc]=ismember(keyS,keyU);
    assert(all(tf)&&all(nC(loc)==S.candidate_count)&& ...
        all(rank1(loc)==1), ...
        'stage7a7:CandidateRows','Candidate audit rows/rank mismatch.');
    check_summary(S,Q,false);
    check_summary(S,T,true);
    pair=strcmp(string(S.split),'T_inlib');
    ids=unique(string(S.sample_id(pair)));
    for k=1:numel(ids)
        x=S(pair&string(S.sample_id)==ids(k),:);
        assert(numel(unique(x.parameter_seed))==1&& ...
            numel(unique(x.noise_seed))==1&& ...
            numel(unique(x.true_main_scale))==1, ...
            'stage7a7:Pairing','Views/flows did not use paired scenarios.');
    end
    fprintf('PASS test_stage7a7_result_integrity %s %s\n',mode,condition);
end
function key=join_key(T)
    key=strcat(string(T.sample_id),'|',string(T.scheme),'|', ...
        string(T.flow));
end
function check_summary(S,Q,by_topology)
    for j=1:height(Q)
        ix=strcmp(string(S.split),string(Q.split(j)))& ...
            strcmp(string(S.scheme),string(Q.scheme(j)))& ...
            strcmp(string(S.flow),string(Q.flow(j)));
        if by_topology
            ix=ix&strcmp(string(S.scenario),string(Q.scenario(j)));
        end
        x=S(ix,:);n=height(x);
        assert(n==Q.n(j)&& ...
            sum(x.correct_unique)==Q.correct_unique_k(j)&& ...
            sum(x.false_unique)==Q.false_unique_k(j)&& ...
            sum(strcmp(string(x.state),'REJECTED'))==Q.rejected_k(j)&& ...
            sum(strcmp(string(x.state),'MULTIPLE_AMBIGUOUS'))== ...
                Q.ambiguous_k(j)&& ...
            sum(strcmp(string(x.state),'LOW_CONFIDENCE'))== ...
                Q.low_confidence_k(j)&& ...
            sum(x.generated_by_edit)==Q.generated_by_edit_k(j)&& ...
            sum(x.added_by_completion)==Q.added_by_completion_k(j)&& ...
            sum(x.active)==Q.active_k(j)&& ...
            sum(x.truth_in_set)==Q.truth_in_set_k(j), ...
            'stage7a7:SummaryMismatch','Summary row %d differs.',j);
        [lo,hi]=stage7a4_wilson(sum(x.false_unique),n);
        assert(abs(lo-Q.false_unique_low(j))<1e-10&& ...
            abs(hi-Q.false_unique_high(j))<1e-10, ...
            'stage7a7:Wilson','Interval row %d differs.',j);
    end
end
