function test_stage7a13_result_integrity(root,mode,run_id)
%TEST_STAGE7A13_RESULT_INTEGRITY Recompute archived Stage 7A.13 counts.
%   This check reads an existing run and never changes scientific results.
    if nargin<1||isempty(root)
        root=fileparts(fileparts(mfilename('fullpath')));
    end
    if nargin<2||isempty(mode),mode='smoke';end
    if nargin<3||isempty(run_id),run_id='smoke2';end
    out=fullfile(root,'results','data','stage7a_13',mode,run_id);
    x=readtable(fullfile(out,'samples.csv'),'TextType','string');
    y=readtable(fullfile(out,'summary.csv'),'TextType','string');
    graphs=readtable(fullfile(out,'graph_catalog.csv'),'TextType','string');
    mirror=readtable(fullfile(out,'mirror_control.csv'), ...
        'TextType','string');
    metadata=readtable(fullfile(out,'metadata.csv'),'TextType','string');
    assert(height(x)==height(y)*y.n(1) && ...
        all(y.n==y.n(1)) && height(metadata)==1, ...
        'Unexpected sample or summary shape.');
    assert(isempty(intersect(graphs.signature(graphs.calibration~=0), ...
        graphs.signature(graphs.final_test~=0))), ...
        'Calibration and final-test physical graphs overlap.');
    assert(all(~x.correct_unique(~x.truth_generated)), ...
        'A missing true candidate was counted as correct unique.');
    assert(all(~x.correct_unique(~x.truth_in_set)), ...
        'A true graph outside the set was counted as correct unique.');
    assert(all(~x.false_unique(x.correct_unique~=0)) && ...
        all(x.correct_unique | x.false_unique | ...
        x.decision_state~="UNIQUE_CONFIDENT"), ...
        'Unique-output labels are inconsistent.');
    assert(all(mirror.decision_state~="UNIQUE_CONFIDENT"), ...
        'Mirror positive control was forced unique.');
    for i=1:height(y)
        row=y(i,:);
        group=x(x.condition==row.condition & ...
            x.method==row.method & x.truth_id==row.truth_id,:);
        assert(height(group)==row.n, ...
            'A summary group has the wrong denominator.');
        assert(row.initial_library_in==all(group.initial_library_in) && ...
            row.searchable_in==all(group.searchable_in), ...
            'Summary graph stratum differs from sample rows.');
        verify_count(row.generated_truth_k,nnz(group.truth_generated));
        verify_count(row.generated_and_h50_pass_k, ...
            nnz(group.truth_generated & group.truth_h50_class_pass));
        verify_count(row.truth_in_set_k,nnz(group.truth_in_set));
        verify_count(row.correct_unique_k,nnz(group.correct_unique));
        verify_count(row.false_unique_k,nnz(group.false_unique));
        verify_count(row.nonempty_set_k,nnz(group.candidate_set_size>0));
        verify_count(row.ambiguous_k, ...
            nnz(group.decision_state=="MULTIPLE_AMBIGUOUS"));
        verify_count(row.low_confidence_k, ...
            nnz(group.decision_state=="LOW_CONFIDENCE"));
        verify_count(row.rejected_k, ...
            nnz(group.decision_state=="REJECTED"));
        verify_count(row.pruned_guard_k,nnz(group.pruned_guard_active));
        assert(abs(row.mean_candidate_count-mean(group.candidate_count)) ...
            <1e-10 && abs(row.mean_set_size- ...
            mean(group.candidate_set_size))<1e-10 && ...
            abs(row.mean_generation_wall_s- ...
            mean(group.generation_wall_s))<1e-10 && ...
            abs(row.mean_confirmation_wall_s- ...
            mean(group.confirmation_wall_s))<1e-10, ...
            'Summary mean differs from sample rows.');
    end
    fprintf('PASS test_stage7a13_result_integrity %s/%s: ',mode,run_id);
    fprintf('%d samples, %d groups.\n',height(x),height(y));
end

function verify_count(actual,expected)
    assert(actual==expected,'Summary count differs from sample rows.');
end
