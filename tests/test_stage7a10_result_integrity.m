function test_stage7a10_result_integrity(root,run_id)
%TEST_STAGE7A10_RESULT_INTEGRITY Recount all Stage 7A.10 formal CSV rows.
    if nargin<1||isempty(root),root=fileparts(fileparts(mfilename('fullpath')));end
    if nargin<2||isempty(run_id),run_id='confirm1';end
    folder=fullfile(root,'results','data','stage7a_10','formal',run_id);
    samples=readtable(fullfile(folder,'samples.csv'),'TextType','string');
    summary=readtable(fullfile(folder,'summary.csv'),'TextType','string');
    catalog=readtable(fullfile(folder,'topologies.csv'),'TextType','string');
    calibration=readtable(fullfile(folder,'calibration.csv'),'TextType','string');
    selection=readtable(fullfile(folder,'view_selection.csv'),'TextType','string');
    metadata=readtable(fullfile(folder,'metadata.csv'),'TextType','string');
    assert(height(samples)==12960&&height(catalog)==8&& ...
        height(calibration)==18&&height(selection)==75&&height(metadata)==1, ...
        'Stage 7A.10 artifact row counts differ from protocol.');
    assert(metadata.parallel_workers==0&& ...
        metadata.baseline_commit=="1c7ae4a40f641d37c44a35b3d64278af19fcc98f", ...
        'Runtime or baseline identity differs.');
    if strcmp(run_id,'confirm1')
        assert(metadata.T_seed==900000000&&metadata.stress_seed==910000000, ...
            'Confirmatory T seed differs from the frozen protocol amendment.');
    end
    assert(numel(unique(samples.noise_seed(samples.scenario=="T20")))==240, ...
        'T20 does not contain 240 distinct physical observation seeds.');
    assert(all(ismember(samples.decision_state, ...
        ["UNIQUE_CONFIDENT","MULTIPLE_AMBIGUOUS","LOW_CONFIDENCE","REJECTED"])), ...
        'Unexpected decision state.');
    assert(~any(samples.correct_unique & samples.false_unique)&& ...
        ~any(samples.correct_unique & ~samples.truth_in_library), ...
        'Incorrect unique-result denominator.');
    assert(~any(samples.truth_in_set & ~samples.truth_in_library), ...
        'Out-of-library truth cannot enter the candidate set.');
    assert(~any(samples.method=="D_adaptive" & ...
        samples.decision_reason=="empty_first_set" & ...
        samples.candidate_set_size~=0), ...
        'Empty first-stage set must remain empty.');
    assert(nnz(catalog.in_original_three)==3&& ...
        nnz(catalog.in_expanded_six)==6&& ...
        all(calibration.A0_seed~=calibration.A1_seed)&& ...
        all(calibration.A1_seed~=calibration.F_seed), ...
        'Candidate or calibration split identity mismatch.');
    controls=readtable(fullfile(root,'results','data','stage7a_10', ...
        'formal','controls',run_id,'samples.csv'),'TextType','string');
    ports=readtable(fullfile(root,'results','data','stage7a_10', ...
        'formal','ports_off',run_id,'samples.csv'),'TextType','string');
    assert(height(controls)==90&&nnz(controls.false_unique)==0&& ...
        height(ports)==720&&numel(unique(ports.noise_seed))==240, ...
        'Positive control or no-node-port row counts differ.');
    main_t=samples(samples.scenario=="T20" & ...
        samples.method=="D_adaptive",:);
    for i=1:height(ports)
        pair=main_t(main_t.noise_seed==ports.noise_seed(i) & ...
            main_t.library==ports.library(i) & ...
            main_t.truth_id==ports.truth_id(i),:);
        assert(height(pair)==1,'No-node-port sample lacks a paired main T row.');
    end
    for k=1:height(summary)
        r=summary(k,:);
        mask=samples.scenario==r.scenario & samples.method==r.method & ...
            samples.library==r.library;
        if r.truth_group~="ALL",mask=mask & samples.truth_id==r.truth_group;end
        z=samples(mask,:);
        assert(height(z)==r.n&&nnz(z.truth_in_library)==r.truth_in_library_n&& ...
            nnz(z.correct_unique)==r.correct_unique_k&& ...
            nnz(z.false_unique)==r.false_unique_k&& ...
            nnz(z.truth_in_set)==r.truth_in_set_k&& ...
            nnz(z.candidate_set_size>0)==r.nonempty_set_k&& ...
            nnz(z.decision_state=="MULTIPLE_AMBIGUOUS")==r.ambiguous_k&& ...
            nnz(z.decision_state=="LOW_CONFIDENCE")==r.low_confidence_k&& ...
            nnz(z.decision_state=="REJECTED")==r.rejected_k, ...
            'A Stage 7A.10 summary row disagrees with raw samples.');
    end
    archive=fullfile(root,'results','data','stage7a_10','archive');
    if exist(archive,'dir')==7
        lists={'source_inventory.csv','artifact_manifest.csv'};
        for j=1:numel(lists)
            p=fullfile(archive,lists{j});
            assert(exist(p,'file')==2,'Stage 7A.10 manifest is missing.');
            inventory=readtable(p,'TextType','string');
            for i=1:height(inventory)
                item=fullfile(root,strrep(char(inventory.relative_path(i)),'/',filesep));
                assert(exist(item,'file')==2,'Inventoried file is missing.');
                info=dir(item);
                assert(info.bytes==inventory.size_bytes(i)&& ...
                    strcmp(stage4a7_2_r2_sha256_file(item), ...
                    char(inventory.sha256(i))), ...
                    'Inventoried Stage 7A.10 SHA-256 mismatch.');
            end
        end
    end
    fprintf('PASS test_stage7a10_result_integrity: %d samples, %d summary rows\n', ...
        height(samples),height(summary));
end
