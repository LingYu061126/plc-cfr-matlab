function test_stage7a6_result_integrity(root,mode,budget)
%TEST_STAGE7A6_RESULT_INTEGRITY Check the isolated budget output and labels.
    if nargin<1||isempty(root)
        root=fileparts(fileparts(mfilename('fullpath')));
    end
    if nargin<2||isempty(mode),mode='smoke';end
    if nargin<3||isempty(budget),budget=3;end
    output_mode=mode;
    if strcmp(mode,'smoke'),output_mode='smoke_v3';end
    dirout=fullfile(root,'results','data','stage7a_6', ...
        output_mode,sprintf('budget_%02d',budget));
    names={'samples.csv','candidate_audit.csv','summary.csv', ...
        'topology_summary.csv','source_inventory.csv', ...
        'artifact_manifest.csv', ...
        'calibration.csv','topology_inventory.csv','seed_manifest.csv', ...
        'metadata.csv','config_snapshot.mat'};
    for k=1:numel(names)
        assert(exist(fullfile(dirout,names{k}),'file')==2, ...
            'stage7a6:MissingArtifact','Missing %s.',names{k});
    end
    s=readtable(fullfile(dirout,'samples.csv'),'TextType','string');
    c=readtable(fullfile(dirout,'candidate_audit.csv'),'TextType','string');
    q=readtable(fullfile(dirout,'summary.csv'),'TextType','string');
    t=readtable(fullfile(dirout,'topology_inventory.csv'),'TextType','string');
    m=readtable(fullfile(dirout,'metadata.csv'),'TextType','string');
    source=readtable(fullfile(dirout,'source_inventory.csv'),'TextType','string');
    artifact=readtable(fullfile(dirout,'artifact_manifest.csv'),'TextType','string');
    assert(height(t)==19&&sum(t.in_expanded_pool)==17&& ...
        sum(t.in_old_ten)==10);
    assert(height(s)>0&&height(c)==sum(s.candidate_count));
    assert(all(ismember(unique(s.state), ...
        ["UNIQUE_CONFIDENT","MULTIPLE_AMBIGUOUS", ...
        "LOW_CONFIDENCE","REJECTED"])));
    assert(all(s.correct_unique==(s.state=="UNIQUE_CONFIDENT" & ...
        s.best_candidate==s.truth_id)));
    assert(all(s.false_unique==(s.state=="UNIQUE_CONFIDENT" & ...
        s.best_candidate~=s.truth_id)));
    assert(~any(s.correct_unique&s.false_unique));
    assert(all(s.candidate_count<=max(3,budget)));
    assert(all(~s.generated(s.flow=="B")));
    assert(~any(s.truth_in_search_pool(s.split=="T_grammar_out")), ...
        'Grammar-out truth entered the candidate pool.');
    assert(~any(s.correct_unique(s.split=="T_grammar_out")), ...
        'A grammar-out truth cannot be correctly selected from this pool.');
    assert(~any(s.pruned&~s.generated)&& ...
        ~any(s.not_generated&s.generated), ...
        'Generation and post-generation pruning were conflated.');
    assert(all(s.domain_out(s.split=="T_domain")));
    assert(m.budget==budget&&m.pool_size==17&& ...
        m.test_observations*6==height(s));
    verify_hashes(root,source);
    verify_hashes(root,artifact);
    for k=1:height(q)
        ix=s.split==q.split(k)&s.scheme==q.scheme(k)&s.flow==q.flow(k);
        x=s(ix,:);
        assert(height(x)==q.n(k)&& ...
            sum(x.correct_unique)==q.correct_unique_k(k)&& ...
            sum(x.false_unique)==q.false_unique_k(k)&& ...
            sum(x.state=="REJECTED")==q.rejected_k(k)&& ...
            sum(x.state=="MULTIPLE_AMBIGUOUS")==q.ambiguous_k(k)&& ...
            sum(x.state=="LOW_CONFIDENCE")==q.low_confidence_k(k)&& ...
            sum(x.generated)==q.truth_generated_k(k)&& ...
            sum(x.not_generated)==q.truth_not_generated_k(k)&& ...
            sum(x.pruned)==q.truth_pruned_k(k), ...
            'Stage 7A.6 summary disagrees with per-sample records.');
    end
    for k=1:height(s)
        ix=c.sample_id==s.sample_id(k)&c.scheme==s.scheme(k)& ...
            c.flow==s.flow(k)&c.budget==s.budget(k);
        assert(sum(ix)==s.candidate_count(k)&& ...
            sum(c.in_candidate_set(ix))==s.set_size(k), ...
            'Candidate/sample identity or set size mismatch.');
    end
    fprintf('PASS test_stage7a6_result_integrity (%s budget %d): %d decisions\n', ...
        mode,budget,height(s));
end
function verify_hashes(root,inventory)
    for k=1:height(inventory)
        path=fullfile(root,char(inventory.relative_path(k)));
        assert(exist(path,'file')==2,'stage7a6:ManifestMissing');
        [status,out]=system(sprintf('sha256sum "%s"',path));
        assert(status==0,'stage7a6:HashCommand');
        actual=regexp(strtrim(out),'^[0-9a-f]{64}','match','once');
        assert(strcmp(actual,inventory.sha256(k)), ...
            'stage7a6:ManifestMismatch','SHA mismatch: %s.',path);
    end
end
