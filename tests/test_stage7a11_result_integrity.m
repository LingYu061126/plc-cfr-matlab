function test_stage7a11_result_integrity(root,mode,run_id)
%TEST_STAGE7A11_RESULT_INTEGRITY Recompute paired counts from saved CSV.
    if nargin<1||isempty(root),root=fileparts(fileparts(mfilename('fullpath')));end
    if nargin<2||isempty(mode),mode='smoke';end
    if nargin<3||isempty(run_id),run_id='smoke1';end
    path=fullfile(root,'results','data','stage7a_11',mode,run_id);
    samples=readtable(fullfile(path,'samples.csv'),'TextType','string', ...
        'Delimiter',',');
    summary=readtable(fullfile(path,'summary.csv'),'TextType','string', ...
        'Delimiter',',');
    audit=readtable(fullfile(path,'candidate_audit.csv'),'TextType','string', ...
        'Delimiter',',');
    graph=readtable(fullfile(path,'graph_catalog.csv'),'TextType','string', ...
        'Delimiter',',');
    meta=readtable(fullfile(path,'metadata.csv'),'TextType','string', ...
        'Delimiter',',');
    snap=load(fullfile(path,'config_snapshot.mat'),'cfg','fixed_cal','new_cal');
    assert(meta.parallel_workers==0 && ...
        meta.fixed_test_seed==snap.cfg.seed_fixed_T && ...
        meta.new_test_seed==snap.cfg.seed_new_T, ...
        'Stage 7A.11 metadata/seed identity mismatch.');
    assert(numel(unique([snap.cfg.seed_E snap.cfg.seed_A0 snap.cfg.seed_A1 ...
        snap.cfg.seed_F snap.cfg.seed_fixed_T snap.cfg.seed_new_T]))==6, ...
        'Calibration/test seed bases overlap.');
    n=snap.cfg.n_T_per_topology;
    assert(height(samples)==n*(8*3*6+4*5) && ...
        height(graph)==18,'Stage 7A.11 row/graph count mismatch.');
    assert(numel(unique(graph.signature(graph.batch=="fixed_graph_new_noise")))==8 ...
        && numel(unique(graph.signature(graph.batch=="new_structure_diagnostic")))==10, ...
        'Physical graph signatures are not distinct within each batch.');
    states=["UNIQUE_CONFIDENT","MULTIPLE_AMBIGUOUS", ...
        "LOW_CONFIDENCE","REJECTED"];
    assert(all(ismember(samples.decision_state,states)), ...
        'Invalid four-state decision.');
    joint=samples.method=="J_joint_select";
    assert(all(samples.truth_in_set(joint)<=samples.truth_in_first(joint)), ...
        'Final truth coverage exceeds first-stage coverage.');
    for i=find(joint)'
        first=split(samples.first_set(i),',');last=split(samples.candidate_set(i),',');
        first(first=="")=[];last(last=="")=[];
        assert(all(ismember(last,first)) && ...
            numel(last)==samples.candidate_set_size(i), ...
            'J final candidate set is not nested.');
    end
    assert(height(audit)>0 && ...
        all(ismember(audit.method,["D_frozen","D_samecal","J_joint_select"])), ...
        'Candidate audit identity mismatch.');
    for i=1:height(summary)
        s=summary(i,:);mask=samples.batch==s.batch & ...
            samples.library==s.library & samples.method==s.method;
        if s.truth_id~="ALL",mask=mask & samples.truth_id==s.truth_id;end
        x=samples(mask,:);in=x.truth_in_library;out=~in;
        assert(height(x)==s.n && nnz(in)==s.in_library_n && ...
            nnz(out)==s.out_library_n && ...
            nnz(x.correct_unique & in)==s.correct_unique_k && ...
            nnz(x.truth_in_set & in)==s.truth_in_set_k && ...
            nnz(x.false_unique & out)==s.false_unique_out_k && ...
            nnz(x.candidate_set_size>0 & out)==s.nonempty_out_k, ...
            'Summary does not match sample denominators or numerators.');
    end
    fprintf('PASS test_stage7a11_result_integrity %s %s: %d samples, %d groups\n', ...
        mode,run_id,height(samples),height(summary));
end
