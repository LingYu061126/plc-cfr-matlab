function summary=exp_stage6b_robustness(root,mode)
%EXP_STAGE6B_ROBUSTNESS Run all four Stage 6B controlled experiments.
    if nargin<1||isempty(root),root=fileparts(fileparts(mfilename('fullpath')));end
    if nargin<2||isempty(mode),mode='formal';end
    addpath(fullfile(root,'src'),fullfile(root,'config'),fullfile(root,'experiments'));
    base=default_config(root);sc=stage6b_robustness_config(base,mode);
    if strcmp(sc.mode,'formal'),out=sc.output_root;else,out=fullfile(sc.output_root,sc.mode);end
    if exist(out,'dir')~=7,mkdir(out);end
    whole=tic;t=tic;[prior_rows,prior_summary]=exp_stage6b_prior_sensitivity(root,mode);prior_time=toc(t);
    t=tic;[scale_rows,scale_samples]=exp_stage6b_candidate_scale(root,mode);scale_time=toc(t);
    t=tic;[parameter_rows,parameter_summary]=exp_stage6b_parameter_uncertainty(root,mode);parameter_time=toc(t);
    t=tic;[identifiability_rows,distance_matrix]=exp_stage6b_identifiability(root,mode);identifiability_time=toc(t);
    total=toc(whole);
    runtime=struct('mode',mode,'prior_sensitivity_time_s',prior_time,'candidate_scale_time_s',scale_time, ...
        'parameter_uncertainty_time_s',parameter_time,'identifiability_time_s',identifiability_time, ...
        'total_time_s',total,'use_parallel',false,'worker_count',1);
    summary=struct('stage_name','Stage 6B','mode',mode,'status',[mode '_completed'], ...
        'prior_sample_count',numel(prior_rows),'scale_sample_count',numel(scale_samples), ...
        'parameter_sample_count',numel(parameter_rows),'identifiability_scenario_count',numel(identifiability_rows), ...
        'total_runtime_s',total,'stage4a_frozen_source_modified',false, ...
        'stage5b1_source_modified',false,'stage6a_generation_source_modified',false, ...
        'validation_scope',sc.validation_scope);
    writetable(struct2table(runtime),fullfile(out,'stage6b_runtime.csv'));
    save(fullfile(out,'stage6b_results.mat'),'summary','runtime','prior_rows','prior_summary', ...
        'scale_rows','scale_samples','parameter_rows','parameter_summary', ...
        'identifiability_rows','distance_matrix','sc','-v7');
    fprintf('Stage 6B %s completed: prior=%d scale=%d parameter=%d identifiability=%d in %.3f s.\n', ...
        mode,numel(prior_rows),numel(scale_samples),numel(parameter_rows),numel(identifiability_rows),total);
end
