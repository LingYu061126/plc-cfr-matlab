function out=exp_stage4a3_open_set_audit(cfg,sc)
if nargin<1||isempty(cfg),cfg=default_config(fileparts(fileparts(mfilename('fullpath'))));end
if nargin<2,sc=stage4a3_open_set_config(cfg);end
ensure_result_dirs(cfg); bank=generate_stage4a3_trial_bank(cfg,sc);
grid=topology_parameter_grid(sc.parameter_search);
D=struct([]); S=struct([]); T=empty_threshold_rows(); F=empty_frequency_rows(); E=empty_equivalence_rows(); tic;
for fg=1:numel(sc.grids)
 fprintf('Stage4A3 grid %s: calibration and test matching\n',sc.grids(fg).id);
 f=sc.grids(fg).frequency_hz;
 F(end+1)=frequency_row(sc.grids(fg),sc); %#ok<AGROW>
 p0=generate_prior_constrained_candidates(sc.generator,sc.scenarios(1).asset_prior);
 opt=baseopt(sc,struct('residual',Inf,'margin',0)); cal=bank(strcmp({bank.split},'calibration'));
 cd=runset(cal,p0,f,grid,cfg,opt,sc.grids(fg).id,'P0_no_prior'); th=calibrate_open_set_thresholds(cd,sc);
 for ss=1:numel(sc.scenarios)
  fprintf('  scenario %s\n',sc.scenarios(ss).id);
  c=generate_prior_constrained_candidates(sc.generator,sc.scenarios(ss).asset_prior);
  test=bank(strcmp({bank.split},'test'));
  dec=runset(test,c,f,grid,cfg,baseopt(sc,th),sc.grids(fg).id,sc.scenarios(ss).id);
  lab=labels(test,c,sc.grids(fg).id,sc.scenarios(ss).id,sc);
  if isempty(D), D=dec; else, D=[D;dec]; end %#ok<AGROW>
  if isempty(S), S=lab; else, S=[S;lab]; end %#ok<AGROW>
  if ~isempty(dec), E=[E;eqrows(dec,sc.grids(fg).id,sc.scenarios(ss).id,sc)]; end %#ok<AGROW>
 end
 T(end+1)=threshold_row(sc.grids(fg).id,th,sc); %#ok<AGROW>
end
M=evaluate_stage4a3_open_set_metrics(D,S);
writetable(struct2table(decisionrows(D)),fullfile(cfg.results_data,'stage4a3_match_decisions.csv'));
writetable(struct2table(S),fullfile(cfg.results_data,'stage4a3_scoring_labels.csv'));
writetable(struct2table(T),fullfile(cfg.results_data,'stage4a3_thresholds.csv'));
writetable(struct2table(M),fullfile(cfg.results_data,'stage4a3_metrics.csv'));
writetable(struct2table(bankrows(bank,sc)),fullfile(cfg.results_data,'stage4a3_trial_bank.csv'));
writetable(struct2table(F),fullfile(cfg.results_data,'stage4a3_frequency_grid_manifest.csv'));
writetable(struct2table(E),fullfile(cfg.results_data,'stage4a3_equivalence_audit.csv'));
save(fullfile(cfg.results_data,'stage4a3_results.mat'),'sc','bank','D','S','T','M','F','E','grid');
out=struct('runtime_s',toc,'decisions',D,'metrics',M);
end
function o=baseopt(s,t),o=struct('measurement_kind',s.measurement_kind,'tie_tolerance',s.tie_tolerance,'feature',s.feature,'weights',s.weights,'batch_size',s.batch_size,'thresholds',t,'config_hash',s.config_hash);end
function d=runset(b,c,f,g,cfg,o,gridid,scenario)
d=struct([]); o.candidate_count_before_prior=numel(c);
for i=1:numel(b)
 [n,cf]=topology_apply_parameters(b(i).truth_network,cfg,b(i).truth_theta);
 [m,~]=plc_measurement_bundle(o.measurement_kind,n,b(i).truth_theta,cf);
 v=plc_multiview_response(f,n,m,cf);
 r=match_composite_topology_library_open_set(v,f,c,g,cfg,o);
 % Scenario and truth labels stay outside the matcher output and are joined
 % offline through the row order and sample_id.
 r.sample_id=b(i).sample_id; r.grid_id=gridid;
 if isempty(d), d=r; else, d(end+1)=r; end %#ok<AGROW>
end
d=d(:);
end
function s=labels(b,c,gid,scenario,sc)
s=struct('sample_id',{},'grid_id',{},'scenario_id',{},'truth_topology_id',{}, ...
    'category',{},'coverage_status',{},'truth_main_length_scale',{}, ...
    'truth_branch_length_scale',{},'truth_branch_load_scale',{}, ...
    'truth_source_impedance_ohm',{},'truth_receiver_impedance_ohm',{}, ...
    'config_hash',{});
ids={c.topology_id};
for i=1:numel(b)
 covered=any(strcmp(ids,b(i).truth_topology_id))&&strcmp(b(i).category,'in_library_continuous');
 t=b(i).truth_theta;
 s(i)=struct('sample_id',b(i).sample_id,'grid_id',gid,'scenario_id',scenario, ...
  'truth_topology_id',b(i).truth_topology_id,'category',b(i).category, ...
  'coverage_status',tern(covered,'covered','out_of_library_or_excluded'), ...
  'truth_main_length_scale',t.main_length_scale,'truth_branch_length_scale',t.branch_length_scale, ...
  'truth_branch_load_scale',t.branch_load_scale,'truth_source_impedance_ohm',t.source_impedance_ohm, ...
  'truth_receiver_impedance_ohm',t.receiver_impedance_ohm,'config_hash',sc.config_hash);
end
s=s(:);
end
function x=tern(c,a,b),if c,x=a;else,x=b;end,end
function r=decisionrows(d)
r=repmat(struct('sample_id','','grid_id','','decision','','best_template_id','', ...
  'best_topology_id','','best_equivalence_class','','best_parameter_values','', ...
  'best_distance',NaN, ...
 'second_competing_class','','second_distance',NaN,'margin',NaN, ...
 'candidate_count_before_prior',0,'candidate_count_after_prior',0, ...
 'parameter_template_count',0,'composite_template_count',0,'streaming_used',true, ...
 'residual_threshold',NaN,'margin_threshold',NaN,'config_hash',''),numel(d),1);
for k=1:numel(d)
 r(k)=struct('sample_id',d(k).sample_id,'grid_id',d(k).grid_id,'decision',d(k).decision, ...
  'best_template_id',d(k).best_template_id,'best_topology_id',d(k).best_topology_id, ...
  'best_equivalence_class',d(k).best_equivalence_class,'best_parameter_values',theta_text(d(k).best_parameter_values), ...
  'best_distance',d(k).best_distance, ...
  'second_competing_class',d(k).second_competing_class,'second_distance',d(k).second_distance, ...
  'margin',d(k).margin,'candidate_count_before_prior',d(k).candidate_count_before_prior, ...
  'candidate_count_after_prior',d(k).candidate_count_after_prior, ...
  'parameter_template_count',d(k).parameter_template_count, ...
  'composite_template_count',d(k).composite_template_count,'streaming_used',d(k).streaming_used, ...
  'residual_threshold',d(k).thresholds.residual,'margin_threshold',d(k).thresholds.margin, ...
  'config_hash',getfield_default(d(k),'config_hash',''));
end
end
function r=bankrows(b,sc)
r=repmat(struct('sample_id','','split','','category','','truth_topology_id','', ...
 'config_hash',''),numel(b),1);
for k=1:numel(b),r(k)=struct('sample_id',b(k).sample_id,'split',b(k).split, ...
 'category',b(k).category,'truth_topology_id',b(k).truth_topology_id, ...
 'config_hash',sc.config_hash);end
end
function r=empty_threshold_rows()
r=repmat(struct('grid_id','','residual_threshold',NaN,'margin_threshold',NaN, ...
 'calibration_count',0,'quantile',NaN,'safety_factor',NaN,'config_hash',''),0,1);
end
function r=threshold_row(g,t,sc)
r=struct('grid_id',g,'residual_threshold',t.residual,'margin_threshold',t.margin, ...
 'calibration_count',t.sample_count,'quantile',t.quantile,'safety_factor',t.safety_factor, ...
 'config_hash',sc.config_hash);
end
function r=empty_frequency_rows()
r=repmat(struct('grid_id','','source','','nfft',0,'sample_rate_hz',NaN, ...
 'active_bin_count',0,'frequency_count',0,'frequency_min_hz',NaN, ...
 'frequency_max_hz',NaN,'frequency_spacing_hz',NaN,'config_hash',''),0,1);
end
function r=frequency_row(g,sc)
f=g.frequency_hz(:).'; diffs=diff(f); if isempty(diffs),df=NaN;else,df=median(diffs);end
r=struct('grid_id',g.id,'source',g.source,'nfft',g.nfft, ...
 'sample_rate_hz',g.sample_rate_hz,'active_bin_count',numel(g.active_bin_1based), ...
 'frequency_count',numel(f),'frequency_min_hz',min(f),'frequency_max_hz',max(f), ...
 'frequency_spacing_hz',df,'config_hash',sc.config_hash);
end
function r=empty_equivalence_rows()
r=repmat(struct('grid_id','','scenario_id','','equivalence_class','', ...
 'member_count',0,'member_topology_ids','','candidate_count',0, ...
 'tie_tolerance',NaN,'config_hash',''),0,1);
end
function r=eqrows(d,gid,scenario,sc)
if isempty(d)||~isfield(d(1),'class_audit')||isempty(fieldnames(d(1).class_audit)),r=empty_equivalence_rows();return,end
a=d(1).class_audit; c=a.core; r=repmat(struct('grid_id','','scenario_id','', ...
 'equivalence_class','','member_count',0,'member_topology_ids','', ...
 'candidate_count',0,'tie_tolerance',NaN,'config_hash',''),numel(c.class_members),1);
for k=1:numel(c.class_members)
 ids=c.class_members{k}; r(k)=struct('grid_id',gid,'scenario_id',scenario, ...
  'equivalence_class',c.class_labels{ids(1)},'member_count',numel(ids), ...
  'member_topology_ids',strjoin(d(1).class_audit.equivalence_classes{k}.member_topology_ids,','), ...
  'candidate_count',a.candidate_count,'tie_tolerance',a.tie_tolerance,'config_hash',sc.config_hash);end
end
function v=getfield_default(s,name,default)
if isfield(s,name),v=s.(name);else,v=default;end
end
function x=theta_text(t)
if isempty(t)||~isstruct(t),x='';return,end
x=sprintf('main=%.12g;branch=%.12g;load=%.12g;Zs=%.12g;Zr=%.12g', ...
 t.main_length_scale,t.branch_length_scale,t.branch_load_scale, ...
 t.source_impedance_ohm,t.receiver_impedance_ohm);
end
