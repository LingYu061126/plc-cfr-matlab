function result=exp_stage7a3_library_out_audit(root,mode)
%EXP_STAGE7A3_LIBRARY_OUT_AUDIT Reproduce and test library-out detectability.
%   All scoring receives observations, cached templates and distances only;
%   truth is used in separate generation/audit fields.
    if nargin<1||isempty(root),root=fileparts(fileparts(mfilename('fullpath')));end
    if nargin<2||isempty(mode),mode='formal';end
    addpath(fullfile(root,'src'),fullfile(root,'config'));
    base=default_config(root);cfg=stage7a3_library_out_config(base,mode);
    out=fullfile(cfg.output_root,'formal');figdir=fullfile(cfg.figure_root,'formal');
    if strcmp(mode,'smoke'),out=fullfile(cfg.output_root,'smoke');figdir=fullfile(cfg.figure_root,'smoke');end
    ensure_dir(out);ensure_dir(figdir);whole=tic;
    canonical_dir=fullfile(root,'results','data','stage7a_2','formal');
    canonical_samples=readtable(fullfile(canonical_dir,'stage7a2_samples.csv'),'TextType','string');
    canonical_distances=readtable(fullfile(canonical_dir,'stage7a2_candidate_distances.csv'),'TextType','string');
    stage6b_controls=readtable(fullfile(root,'results','data','stage6b','stage6b_identifiability.csv'),'TextType','string');
    sample_cells={};distance_cells={};spectrum_cells={};threshold_cells={};
    family_inventory={};identity_cells={};seed_cells={};overlap_cells={};
    libraries={};caches={};models={};risk_models={};gates={};
    legacy=cfg.legacy;sc=legacy.stage7a;
    for q=1:3
        library_tic=tic;candidate_rows_before=numel(distance_cells);
        grammar=sc.stage6b.scale.grammars(q);
        lib=stage6b_build_candidate_library('radial_grammar',grammar,base,struct());
        cache=stage7a_build_profile_cache(lib,base,sc);m=numel(lib);
        [m2,m2r,model_identity,risk_row]=build_legacy_models(lib,cache,base,cfg,q);
        extended=extended_grammar(grammar);
        all_extra=uncovered_topologies(extended,lib);
        heldout=select_patterns(all_extra,cfg.library_out_patterns);
        dev_truth=stage7a2_first_library_out(grammar,lib,base);
        qname=['scale_' grammar.scale_id];libraries{q}=lib;caches{q}=cache;
        models{q}=m2;risk_models{q}=m2r;
        inv=inventory_rows(all_extra,heldout,lib,qname);
        family_inventory=[family_inventory;num2cell(inv(:))]; %#ok<AGROW>
        [dev_block,sd]=make_block(lib,dev_truth,cache,base,cfg,q,legacy.seed_library_out, ...
            'historical_library_out',legacy.stress_count,legacy.snr_db,legacy.main_bounds);
        assert_replay(dev_block,cache,m2,m2r,qname,canonical_samples,canonical_distances);
        [sr,dr,fr]=score_block(dev_block,cache,m2,m2r,[],qname,'stage7a2_library_out_replay',true);
        sample_cells=[sample_cells;num2cell(sr(:))];distance_cells=[distance_cells;num2cell(dr(:))]; %#ok<AGROW>
        spectrum_cells=[spectrum_cells;num2cell(fr(:))]; %#ok<AGROW>
        seed_cells=[seed_cells;num2cell(seed_rows(dev_block,qname,'historical_development'))]; %#ok<AGROW>
        % New in-library development split; it is not used to set the gate.
        [dblock,sd2]=make_block(lib,lib,cache,base,cfg,q,cfg.seed_development, ...
            'balanced_in_library',cfg.development_per_candidate,cfg.snr_db,cfg.main_bounds);
        [sr,dr,~]=score_block(dblock,cache,m2,m2r,[],qname,'D_in_library_development',false);
        sample_cells=[sample_cells;num2cell(sr(:))];distance_cells=[distance_cells;num2cell(dr(:))]; %#ok<AGROW>
        seed_cells=[seed_cells;num2cell(seed_rows(dblock,qname,'D_in_library_development'))]; %#ok<AGROW>
        % Independent fit-quality calibration split F.
        [fblock,sf]=make_block(lib,lib,cache,base,cfg,q,cfg.seed_gate_calibration, ...
            'balanced_in_library',cfg.gate_calibration_per_candidate,cfg.snr_db,cfg.main_bounds);
        gate_identity=stage4a4_scientific_config_hash(struct('source_commit',cfg.source_commit, ...
            'library_hash',model_identity.library_hash,'search_hash',model_identity.search_hash, ...
            'split','F_gate_fit_quality','seed_base',cfg.seed_gate_calibration, ...
            'frequency_band_count',cfg.frequency_band_count));
        gate=stage7a3_calibrate_residual_gate(fblock.band_stat,cfg.gate_alpha,gate_identity);
        gates{q}=gate;
        % Historical Stage 7A.2 failures are development diagnostics only;
        % the new cutoff comes from the disjoint F split above.
        [dev_gate_rows,~,~]=score_block(dev_block,cache,m2,m2r,gate,qname, ...
            'stage7a2_library_out_replay',false);
        dev_gate_rows=dev_gate_rows(strcmp({dev_gate_rows.method},'M2R_plus_band_gate'));
        sample_cells=[sample_cells;num2cell(dev_gate_rows(:))]; %#ok<AGROW>
        [sr,dr,~]=score_block(fblock,cache,m2,m2r,gate,qname,'F_gate_calibration_diagnostic',false);
        sample_cells=[sample_cells;num2cell(sr(:))];distance_cells=[distance_cells;num2cell(dr(:))]; %#ok<AGROW>
        seed_cells=[seed_cells;num2cell(seed_rows(fblock,qname,'F_gate_calibration'))]; %#ok<AGROW>
        threshold_cells{end+1}=struct('library',qname,'candidate_count',m, ...
            'statistic',gate.statistic,'alpha',gate.alpha,'calibration_count',gate.calibration_count, ...
            'order_statistic_rank',gate.order_statistic_rank,'threshold',gate.threshold, ...
            'calibration_seed_base',cfg.seed_gate_calibration, ...
            'calibration_identity',gate.identity,'calibration_hash',gate.calibration_hash, ...
            'achieved_calibration_acceptance',mean(fblock.band_stat<=gate.threshold)); %#ok<AGROW>
        % Independent risk audit R. No R result is used to retune the M2R rule.
        [rblock,srsk]=make_block(lib,lib,cache,base,cfg,q,cfg.seed_risk, ...
            'random_in_library',cfg.risk_per_candidate*m,cfg.snr_db,cfg.main_bounds);
        [sr,dr,~]=score_block(rblock,cache,m2,m2r,gate,qname,'R_independent_risk_audit',false);
        sample_cells=[sample_cells;num2cell(sr(:))];distance_cells=[distance_cells;num2cell(dr(:))]; %#ok<AGROW>
        seed_cells=[seed_cells;num2cell(seed_rows(rblock,qname,'R_independent_risk_audit'))]; %#ok<AGROW>
        % Final in-library, SNR-shift and parameter-domain test splits.
        for condition={'T_in_library_20db','T_in_library_10db','T_parameter_out'}
            name=condition{1};snr=cfg.snr_db;bounds=cfg.main_bounds;sampling='balanced_in_library';
            reps=cfg.in_library_test_per_candidate;
            if strcmp(name,'T_in_library_10db'),snr=cfg.shift_snr_db;
            elseif strcmp(name,'T_parameter_out'),sampling='parameter_out';reps=cfg.parameter_out_per_candidate;end
            if strcmp(name,'T_in_library_20db'),seedbase=cfg.seed_in_library_test;
            elseif strcmp(name,'T_in_library_10db'),seedbase=cfg.seed_in_library_snr_shift;
            else,seedbase=cfg.seed_parameter_out;end
            [tb,st]=make_block(lib,lib,cache,base,cfg,q,seedbase,sampling,reps,snr,bounds);
            [sr,dr,~]=score_block(tb,cache,m2,m2r,gate,qname,name,false);
            sample_cells=[sample_cells;num2cell(sr(:))];distance_cells=[distance_cells;num2cell(dr(:))]; %#ok<AGROW>
            seed_cells=[seed_cells;num2cell(seed_rows(tb,qname,name))]; %#ok<AGROW>
        end
        % Final held-out library-out topology families, at 20 dB and 10 dB.
        for snr=[cfg.snr_db cfg.shift_snr_db]
            if snr==cfg.snr_db,seedbase=cfg.seed_ood_20db;scenario='T_library_out_20db';
            else,seedbase=cfg.seed_ood_10db;scenario='T_library_out_10db';end
            [ob,so]=make_block(heldout,heldout,cache,base,cfg,0,seedbase, ...
                'balanced_topology_out',cfg.ood_replicates_per_topology,snr,cfg.main_bounds);
            [sr,dr,fr]=score_block(ob,cache,m2,m2r,gate,qname,scenario,true);
            sample_cells=[sample_cells;num2cell(sr(:))];distance_cells=[distance_cells;num2cell(dr(:))]; %#ok<AGROW>
            spectrum_cells=[spectrum_cells;num2cell(fr(:))]; %#ok<AGROW>
            seed_cells=[seed_cells;num2cell(seed_rows(ob,qname,scenario))]; %#ok<AGROW>
        end
        identity_cells{end+1}=struct('library',qname,'candidate_count',m, ...
            'candidate_order',strjoin(cache.candidate_ids,','), ...
            'library_hash',model_identity.library_hash,'search_hash',model_identity.search_hash, ...
            'stage7a2_calibration_identity',model_identity.identity, ...
            'stage7a2_set_hash',model_identity.set_hash,'stage7a2_evidence_hash',model_identity.evidence_hash, ...
            'evidence_beta',m2.evidence_model.beta, ...
            'evidence_margin_threshold',m2.evidence_model.margin_threshold, ...
            'evidence_top1_confidence_threshold',m2.evidence_model.top1_confidence_threshold, ...
            'evidence_entropy_threshold',m2.evidence_model.normalized_entropy_threshold, ...
            'evidence_reference_sample_count',m2.evidence_model.reference_sample_count, ...
            'stage7a2_risk_count',risk_row.risk_count,'stage7a2_risk_selected',risk_row.unique_selected, ...
            'stage7a2_risk_wrong_unique',risk_row.wrong_unique, ...
            'stage7a2_risk_upper_95',risk_row.upper,'stage7a2_risk_certified',risk_row.certified, ...
            'new_gate_hash',gate.calibration_hash,'new_gate_threshold',gate.threshold, ...
            'cache_bytes',whos_bytes(cache),'cache_build_time_s',cache.build_time_s, ...
            'library_runtime_s',toc(library_tic), ...
            'candidate_distance_rows',numel(distance_cells)-candidate_rows_before, ...
            'profiled_observations_n',(numel(distance_cells)-candidate_rows_before)/m, ...
            'replay_rows',numel(dev_block.seed),'replay_seed_example',dev_block.seed(1)); %#ok<AGROW>
        fprintf('Stage 7A.3 %s: candidates=%d, F n=%d, gate=%.6g, replay verified.\n', ...
            qname,m,gate.calibration_count,gate.threshold);
        %#ok<NASGU> sd sf srsk so st sd2
    end
    samples=vertcat(sample_cells{:});distances=vertcat(distance_cells{:});
    spectra=vertcat(spectrum_cells{:});thresholds=vertcat(threshold_cells{:});
    identities=vertcat(identity_cells{:});inventory=vertcat(family_inventory{:});
    seeds=vertcat(seed_cells{:});
    [pairwise,overlap_spectra]=response_overlap_audit(libraries,caches,base,cfg);
    overlap_cells=num2cell(pairwise(:));spectra=[spectra;overlap_spectra(:)];
    controls=positive_control_audit(root,base,cfg,gates{1},stage6b_controls);
    summaries=summarize_samples(samples);
    family_summaries=summarize_families(samples);
    cluster_summaries=summarize_topology_clusters(family_summaries);
    writetable(struct2table(samples),fullfile(out,'stage7a3_sample_diagnostics.csv'));
    writetable(struct2table(distances),fullfile(out,'stage7a3_candidate_distances.csv'));
    writetable(struct2table(summaries),fullfile(out,'stage7a3_group_summary.csv'));
    writetable(struct2table(family_summaries),fullfile(out,'stage7a3_topology_family_summary.csv'));
    writetable(struct2table(cluster_summaries),fullfile(out,'stage7a3_topology_cluster_summary.csv'));
    writetable(struct2table(inventory),fullfile(out,'stage7a3_library_out_inventory.csv'));
    writetable(struct2table(thresholds),fullfile(out,'stage7a3_gate_calibration.csv'));
    writetable(struct2table(pairwise),fullfile(out,'stage7a3_response_overlap.csv'));
    writetable(struct2table(controls),fullfile(out,'stage7a3_positive_controls.csv'));
    writetable(struct2table(seeds),fullfile(out,'stage7a3_seed_manifest.csv'));
    writetable(struct2table(identities),fullfile(out,'stage7a3_model_identity.csv'));
    writetable(struct2table(spectra),fullfile(out,'stage7a3_residual_spectra.csv'));
    write_source_inventory(root,out,cfg.source_commit);
    snapshot=cfg;snapshot.output_root=relative_output_path(root,out); ...
        snapshot.figure_root=relative_output_path(root,figdir);snapshot.log_root='results/logs/stage7a_3';
    snapshot.legacy.output_root='results/data/stage7a_2/formal';snapshot.legacy.figure_root='results/figures/stage7a_2';snapshot.legacy.log_root='results/logs/stage7a_2';
    snapshot.legacy.stage7a.output_root='results/data/stage7a';snapshot.legacy.stage7a.log_root='results/logs/stage7a';
    snapshot.legacy.stage7a.stage6b.output_root='results/data/stage6b';
    snapshot.legacy.stage7a.stage6b.figure_root='results/figures/stage6b';
    save(fullfile(out,'stage7a3_config_snapshot.mat'),'snapshot','-v7');
    meta=table(string({'source_commit';'mode';'matlab_version';'computer_arch'; ...
        'platform';'use_parallel';'worker_count';'protocol_hash';'sample_rows'; ...
        'candidate_distance_rows';'topology_family_count';'runtime_s';'verification_time_utc'}), ...
        string({cfg.source_commit;mode;version;computer('arch');computer;'0';'0'; ...
        stage4a4_scientific_config_hash(snapshot);num2str(numel(samples)); ...
        num2str(numel(distances));num2str(size(cfg.library_out_patterns,1)); ...
        num2str(toc(whole),17);char(datetime('now','TimeZone','UTC', ...
        'Format','yyyy-MM-dd HH:mm:ss'))}),'VariableNames',{'key','value'});
    writetable(meta,fullfile(out,'stage7a3_metadata.csv'));
    result=struct('mode',mode,'status','completed','sample_rows',numel(samples), ...
        'candidate_distance_rows',numel(distances),'topology_family_count',size(cfg.library_out_patterns,1), ...
        'elapsed_s',toc(whole));
    fprintf('Stage 7A.3 %s completed: %d rows, %d candidate rows, %.3f s.\n', ...
        mode,result.sample_rows,result.candidate_distance_rows,result.elapsed_s);
end

function [m2,m2r,identity,risk]=build_legacy_models(lib,cache,base,cfg,q)
    old=cfg.legacy;sc=old.stage7a;m=numel(lib);ids=cache.candidate_ids;
    lh=stage4a4_scientific_config_hash(struct('ids',{ids},'signatures',{cache.candidate_signatures}));
    sh=stage4a4_scientific_config_hash(struct('search',sc.search,'admissible',{cache.admissible}));
    ident=stage4a4_scientific_config_hash(struct('library',lh,'search',sh, ...
        'frequency_hz',sc.frequency_hz,'score','stage7a_profile_distance_v1'));
    [a,~]=make_block(lib,lib,cache,base,cfg,q,old.seed_set,'balanced_in_library', ...
        old.set_per_class,old.snr_db,old.main_bounds);
    [b,~]=make_block(lib,lib,cache,base,cfg,q,old.seed_evidence,'balanced_in_library', ...
        old.evidence_per_class,old.snr_db,old.main_bounds);
    dt=fixed_quantile(min(a.d,[],2)./a.energy,sc.domain_quantile);
    sm=stage7a2_calibrate_set(a.d,a.truth_index,ids,old.alpha,'class_conditional',ident);
    set_sizes=zeros(size(b.d,1),1);
    for k=1:numel(set_sizes),set_sizes(k)=stage7a2_apply_set(b.d(k,:),sm).set_size;end
    opts=sc.evidence_calibration;opts.candidate_ids=ids;
    evidence=calibrate_stage5b1_decision_metrics(b.d,b.truth_index,set_sizes,opts);
    seedmodel=struct('candidate_ids',{ids},'frequency_hz',sc.frequency_hz, ...
        'identity',ident,'set_model',sm,'evidence_model',evidence, ...
        'domain_threshold',dt,'risk_gate',struct('certified',true));
    [rblock,~]=make_block(lib,lib,cache,base,cfg,q,old.seed_risk,'random_in_library', ...
        old.risk_per_class*m,old.snr_db,old.main_bounds);
    nsel=0;nwrong=0;
    for k=1:numel(rblock.seed)
        z=stage7a2_score_distances(rblock.y(k,:),rblock.d(k,:),seedmodel);
        if strcmp(z.decision_state,'UNIQUE_CONFIDENT')
            nsel=nsel+1;nwrong=nwrong+(z.best_index~=rblock.truth_index(k));
        end
    end
    upper=stage7a2_binomial_upper(nwrong,nsel,old.risk_delta);
    certified=upper<=old.risk_target;
    m2=seedmodel;
    m2r=seedmodel;m2r.risk_gate=struct('certified',certified,'upper',upper, ...
        'unique_selected',nsel,'wrong_unique',nwrong);
    identity=struct('identity',ident,'library_hash',lh,'search_hash',sh, ...
        'set_hash',sm.calibration_hash,'evidence_hash',evidence.calibration_hash);
    risk=struct('risk_count',numel(rblock.seed),'unique_selected',nsel, ...
        'wrong_unique',nwrong,'upper',upper,'certified',certified);
end

function [block,timing]=make_block(library,truth_pool,cache,base,cfg,q,seedbase,sampling,count,snr,bounds)
    t0=tic;m=numel(cache.candidate_ids);nf=numel(cache.frequency_hz);
    if ismember(sampling,{'balanced_in_library','parameter_out'}),n=count*numel(truth_pool);
    elseif strcmp(sampling,'balanced_topology_out'),n=count*numel(truth_pool);
    else,n=count;end
    block=struct('y',complex(zeros(n,nf)),'d',zeros(n,m), ...
        'template_indices',zeros(n,m),'band_stat',zeros(n,1), ...
        'band_relative',zeros(n,4),'energy',zeros(n,1), ...
        'noise_rms',zeros(n,1),'truth_index',NaN(n,1),'truth_pool_index',zeros(n,1), ...
        'truth_signature',{cell(n,1)},'pattern',{cell(n,1)},'seed',zeros(n,1), ...
        'main_scale',zeros(n,1),'snr_db',snr*ones(n,1),'scenario',sampling);
    for v=1:n
        switch sampling
            case {'balanced_in_library','parameter_out'}
                j=ceil(v/count);r=mod(v-1,count)+1;
                seed=seedbase+q*100000+j*1000+r;
            case 'balanced_topology_out'
                j=ceil(v/count);r=mod(v-1,count)+1;seed=seedbase+j*1000+r;
            case 'historical_library_out'
                j=1;seed=seedbase+q*100000+v;
            case 'random_in_library'
                seed=seedbase+q*100000+v;rs=RandStream('mt19937ar','Seed',seed);j=randi(rs,numel(truth_pool));
            otherwise,error('stage7a3:UnknownSampling','Unknown sampling scheme %s.',sampling);
        end
        if ~exist('rs','var')||~strcmp(sampling,'random_in_library'),rs=RandStream('mt19937ar','Seed',seed);end
        if strcmp(sampling,'parameter_out')
            if mod(r,2)==1,local_bounds=cfg.parameter_out_low;else,local_bounds=cfg.parameter_out_high;end
        else,local_bounds=bounds;end
        main=local_bounds(1)+diff(local_bounds)*rand(rs);
        truth=truth_pool(j).network;sig=stage6b_network_signature(truth);
        true_index=find(strcmp(cache.candidate_signatures,sig),1);
        theta=theta_for(main,cfg.legacy.stage7a.search);
        clean=stage6b_forward_cfr(truth,theta,base,cfg.legacy.stage7a.frequency_hz, ...
            cfg.legacy.stage7a.measurement_kind);
        sigma=sqrt(mean(abs(clean).^2)/10^(snr/10)/2);
        y=clean+sigma*(randn(rs,size(clean))+1i*randn(rs,size(clean)));
        p=stage7a_profile_distance(y,cache,cfg.legacy.stage7a.search);
        band=stage7a3_band_residual(y,cache,p);
        block.y(v,:)=y;block.d(v,:)=p.profile_distances;
        block.template_indices(v,:)=p.best_template_indices;
        block.band_stat(v)=band.max_band_relative_residual;
        block.band_relative(v,:)=band.band_relative_residual;
        block.energy(v)=max(sqrt(mean(abs(y).^2)),eps);
        block.noise_rms(v)=sqrt(mean(abs(y-clean).^2));
        block.truth_index(v)=nan_if_empty(true_index);block.truth_pool_index(v)=j;
        block.truth_signature{v}=sig;block.pattern{v}=pattern_text(truth);block.seed(v)=seed;
        block.main_scale(v)=main;
    end
    timing=struct('elapsed_s',toc(t0),'samples',n);
end

function [samples,distances,spectra]=score_block(block,cache,m2,m2r,gate,library,scenario,include_spectrum)
    sample_cells={};dist_cells={};spec_cells={};m=numel(cache.candidate_ids);
    for v=1:numel(block.seed)
        z2=stage7a2_score_distances(block.y(v,:),block.d(v,:),m2);
        z2.calibration_identity=m2.identity;
        z2r=stage7a2_score_distances(block.y(v,:),block.d(v,:),m2r);
        z2r.calibration_identity=m2r.identity;
        zs={z2,z2r};names={'M2','M2R'};
        if ~isempty(gate),zs{3}=stage7a3_apply_residual_gate(z2r,block.band_stat(v),gate);names{3}='M2R_plus_band_gate';end
        for h=1:numel(zs)
            z=zs{h};sample_cells{end+1}=sample_row(block,v,z,names{h},library,scenario,gate); %#ok<AGROW>
        end
        keep=z2.candidate_keep;pv=z2.candidate_p_values;
        ranked=sortrows([block.d(v,:).' (1:m).'],[1 2]);ranks=zeros(1,m);
        distance_min=min(block.d(v,:));
        for k=1:m,ranks(ranked(k,2))=k;end
        for k=1:m
            dist_cells{end+1}=struct('library',library,'scenario',scenario, ...
                'sample_seed',block.seed(v),'truth_signature',block.truth_signature{v}, ...
                'candidate_id',cache.candidate_ids{k}, ...
                'candidate_signature',cache.candidate_signatures{k}, ...
                'profile_distance',block.d(v,k),'rank',ranks(k), ...
                'within_1e_12_of_minimum',abs(block.d(v,k)-distance_min)<=1e-12, ...
                'candidate_p_value',pv(k),'candidate_in_set',keep(k), ...
                'is_truth',isfinite(block.truth_index(v))&&k==block.truth_index(v), ...
                'best_template_index',block.template_indices(v,k), ...
                'best_main_scale',cache.main_scale(block.template_indices(v,k)), ...
                'best_branch_load_scale',cache.branch_load_scale(block.template_indices(v,k))); %#ok<AGROW>
        end
        if include_spectrum
            prof=struct('profile_distances',block.d(v,:), ...
                'best_template_indices',block.template_indices(v,:));
            rs=stage7a3_band_residual(block.y(v,:),cache,prof);
            f=cache.frequency_hz(:);rr=rs.residual_cfr(:);
            for k=1:numel(f)
                spec_cells{end+1}=struct('library',library,'scenario',scenario, ...
                    'sample_seed',block.seed(v),'truth_signature',block.truth_signature{v}, ...
                    'best_candidate',rs.best_candidate,'frequency_hz',f(k), ...
                    'residual_real',real(rr(k)),'residual_imag',imag(rr(k)), ...
                    'residual_magnitude',abs(rr(k))); %#ok<AGROW>
            end
        end
    end
    samples=vertcat(sample_cells{:});distances=vertcat(dist_cells{:});
    if isempty(spec_cells),spectra=repmat(spectrum_row(),0,1);else,spectra=vertcat(spec_cells{:});end
end

function row=sample_row(block,v,z,method,library,scenario,gate)
    ti=block.truth_index(v);inlib=isfinite(ti);best_truth=inlib&&z.best_index==ti;
    hit=false;if inlib&&isfield(z,'candidate_keep'),hit=z.candidate_keep(ti);end
    state=z.decision_state;unique=strcmp(state,'UNIQUE_CONFIDENT');
