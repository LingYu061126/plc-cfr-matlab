function assert_replay(block,cache,m2,m2r,library,canonical,canonical_distances)
    for v=1:numel(block.seed)
        seed=block.seed(v);
        for method={'M2','M2R'}
            if strcmp(method{1},'M2'),canonical_method='M2_class_conditional';
            else,canonical_method='M2R_class_risk_gated';end
            ix=canonical.library==library & canonical.scenario=="library_out" & ...
                canonical.method==canonical_method & canonical.sample_seed==seed;
            if nnz(ix)~=1
                lib_count=nnz(canonical.library==library);
                scen_count=nnz(canonical.library==library & canonical.scenario=="library_out");
                method_count=nnz(canonical.library==library & canonical.scenario=="library_out" & ...
                    canonical.method==canonical_method);
                error('stage7a3:ReplaySampleMissing', ...
                    'Canonical row missing: library=%s method=%s seed=%d counts=%d/%d/%d.', ...
                    library,canonical_method,seed,lib_count,scen_count,method_count);
            end
            if strcmp(method{1},'M2'),z=stage7a2_score_distances(block.y(v,:),block.d(v,:),m2);
            else,z=stage7a2_score_distances(block.y(v,:),block.d(v,:),m2r);end
            c=canonical(ix,:);
            assert(strcmp(z.best_candidate,char(c.best_candidate))&& ...
                strcmp(z.candidate_set,char(c.candidate_set))&& ...
                strcmp(z.decision_state,char(c.decision_state))&& ...
                abs(z.distance-c.d1)<=1e-12&&abs(z.margin-c.margin)<=1e-12&& ...
                abs(z.domain_relative_distance-c.domain_relative_distance)<=1e-12, ...
                'stage7a3:ReplayMismatch','Stage 7A.2 sample replay differs from its canonical row.');
        end
        ix=canonical_distances.library==library & canonical_distances.scenario=="library_out" & ...
            canonical_distances.sample_seed==seed;
        c=canonical_distances(ix,:);
        assert(height(c)==numel(cache.candidate_ids),'stage7a3:ReplayCandidateCount', ...
            'Canonical candidate mapping has an unexpected row count.');
        for k=1:height(c)
            j=find(strcmp(cache.candidate_ids,char(c.candidate_id(k))),1);
            assert(~isempty(j)&&strcmp(cache.candidate_signatures{j},char(c.candidate_signature(k)))&& ...
                abs(block.d(v,j)-c.profile_distance(k))<=1e-12, ...
                'stage7a3:ReplayDistanceMismatch','Candidate ID/signature/distance mapping differs.');
        end
    end
end

function [rows,spectra]=response_overlap_audit(libraries,caches,base,cfg)
    rows=repmat(overlap_row(),0,1);spec_cells={};old=cfg.legacy;sc=old.stage7a;
    for q=1:3
        grammar=sc.stage6b.scale.grammars(q);lib=libraries{q};cache=caches{q};
        extra=stage7a2_first_library_out(grammar,lib,base);
        seed=old.seed_library_out+q*100000+1;rs=RandStream('mt19937ar','Seed',seed);
        main=old.main_bounds(1)+diff(old.main_bounds)*rand(rs);
        theta=theta_for(main,sc.search);truth=extra.network;
        htrue=stage6b_forward_cfr(truth,theta,base,sc.frequency_hz,sc.measurement_kind);
        fixed=zeros(1,numel(lib));fixed_h=cell(1,numel(lib));
        for k=1:numel(lib)
            h=stage6b_forward_cfr(lib(k).network,theta,base,sc.frequency_hz,sc.measurement_kind);
            fixed_h{k}=h;fixed(k)=sqrt(mean(abs(htrue-h).^2));
        end
        [fixed_min,fixed_ix]=min(fixed);
        main_grid=unique(cache.main_scale);load_grid=unique(cache.branch_load_scale);
        [mg,lg]=ndgrid(main_grid,load_grid);pairs=[mg(:) lg(:)];
        true_templates=complex(zeros(size(pairs,1),numel(sc.frequency_hz)));
        for p=1:size(pairs,1)
            th=theta_for(pairs(p,1),sc.search);th.branch_load_scale=pairs(p,2);
            true_templates(p,:)=stage6b_forward_cfr(truth,th,base,sc.frequency_hz,sc.measurement_kind);
        end
        best=Inf;best_ix=NaN;best_true=NaN;best_cand_main=NaN;best_cand_load=NaN;
        for k=1:numel(lib)
            allowed=find(cache.admissible{k});candidate_H=cache.H{k}(allowed,:);
            for p=1:size(true_templates,1)
                dd=sqrt(mean(abs(candidate_H-true_templates(p,:)).^2,2));
                [v,ix]=min(dd);
                if v<best
                    best=v;best_ix=k;best_true=p;best_cand_main=cache.main_scale(allowed(ix));
                    best_cand_load=cache.branch_load_scale(allowed(ix));
                end
            end
        end
        rel=fixed_min/max(sqrt(mean(abs(htrue).^2)),eps);
        optrel=best/max(sqrt(mean(abs(htrue).^2)),eps);
        row=struct('library',['scale_' grammar.scale_id], ...
            'truth_signature',stage6b_network_signature(truth), ...
            'truth_pattern',pattern_text(truth),'seed',seed,'true_main_scale',main, ...
            'frequency_count',numel(sc.frequency_hz),'frequency_min_hz',min(sc.frequency_hz), ...
            'frequency_max_hz',max(sc.frequency_hz), ...
            'source_impedance_ohm',theta.source_impedance_ohm, ...
            'receiver_impedance_ohm',theta.receiver_impedance_ohm, ...
            'fixed_parameter_nearest_candidate',cache.candidate_ids{fixed_ix}, ...
            'fixed_parameter_rms_distance',fixed_min, ...
            'fixed_parameter_relative_distance',rel, ...
            'optimized_pair_nearest_candidate',cache.candidate_ids{best_ix}, ...
            'optimized_pair_rms_distance',best, ...
            'optimized_pair_relative_distance',optrel, ...
            'optimized_truth_main_scale',pairs(best_true,1), ...
            'optimized_truth_load_scale',pairs(best_true,2), ...
            'optimized_candidate_main_scale',best_cand_main, ...
            'optimized_candidate_load_scale',best_cand_load, ...
            'same_parameter_numerical_equivalence',max(abs(htrue-fixed_h{fixed_ix})) / ...
                max(sqrt(mean(abs(htrue).^2)),eps)<=1e-12, ...
            'numerical_equivalence_tolerance',1e-12, ...
            'optimization_grid_count',size(pairs,1));
        rows(end+1)=row; %#ok<AGROW>
        % Save the historical sample's best-fit complex residual spectrum.
        block=make_block(lib,extra,cache,base,cfg,q,old.seed_library_out, ...
            'historical_library_out',1,old.snr_db,old.main_bounds);
        p=struct('profile_distances',block.d(1,:), ...
            'best_template_indices',block.template_indices(1,:));
        band=stage7a3_band_residual(block.y(1,:),cache,p);freq=cache.frequency_hz(:);
        for a=1:numel(freq)
            spec_cells{end+1}=struct('library',grammar.scale_id, ...
                'scenario','seed_560x001_best_fit_residual','sample_seed',block.seed(1), ...
                'truth_signature',stage6b_network_signature(truth), ...
                'best_candidate',band.best_candidate,'frequency_hz',freq(a), ...
                'residual_real',real(band.residual_cfr(a)), ...
                'residual_imag',imag(band.residual_cfr(a)), ...
                'residual_magnitude',abs(band.residual_cfr(a))); %#ok<AGROW>
        end
    end
    spectra=vertcat(spec_cells{:});
end

function rows=positive_control_audit(root,base,cfg,gate,canonical)
    all=topology_candidates(base);t3=all(strcmp({all.id},'T3'));t5=all(strcmp({all.id},'T5'));t4=all(strcmp({all.id},'T4'));
