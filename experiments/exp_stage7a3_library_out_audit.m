            'gate_promoted_to_unique',strcmp(gz.decision_state,'UNIQUE_CONFIDENT')&& ...
                ~strcmp(base_decision.decision_state,'UNIQUE_CONFIDENT'), ...
            'calibration_scope_note','Gate cutoff is transferred only for a one-way logic check, not a new control-library guarantee.');
    end
end

