function [lo,hi]=wilson(k,n)
    if n==0,lo=NaN;hi=NaN;return;end
    z=1.959963984540054;p=k/n;den=1+z^2/n;c=(p+z^2/(2*n))/den;
    r=z*sqrt(p*(1-p)/n+z^2/(4*n^2))/den;lo=max(0,c-r);hi=min(1,c+r);
end
