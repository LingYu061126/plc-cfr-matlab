function result=exp_stage7a1_diagnostic(root,mode)
%EXP_STAGE7A1_DIAGNOSTIC Paired Stage 6B/7A calibration and search audit.
%   Writes only results/data/stage7a_1/<mode>. All archived results are read.
    if nargin<1||isempty(root),root=fileparts(fileparts(mfilename('fullpath')));end
    if nargin<2||isempty(mode),mode='formal';end
    addpath(fullfile(root,'src'),fullfile(root,'config'));
    base=default_config(root);dc=stage7a1_diagnostic_config(base,mode);sc=dc.stage7a;
    out=dc.output_root;if exist(out,'dir')~=7,mkdir(out);end
    started=tic;
    sample_cells={};candidate_cells={};search_cells={};search_candidate_cells={};
    resource_cells={};identity_cells={};
    medium=stage6b_build_candidate_library('radial_grammar', ...
        sc.stage6b.scale.grammars(2),base,struct());
    truth=truth_network(medium,sc.stage6b.truth_branch_nodes);
    truth_signature=stage6b_network_signature(truth);
    [test_y,test_main,test_seed]=new_test_observations(truth,base,dc);
    test_id=stage4a4_scientific_config_hash(struct('role','independent_test', ...
        'seeds',test_seed,'main_bounds',dc.test_main_bounds, ...
        'load_bounds',dc.test_load_bounds,'snr_db',dc.test_snr_db, ...
        'truth_signature',truth_signature,'frequency_hz',sc.frequency_hz));
    archived=table();
    replay_id='not_run';
    if dc.canonical_replay
        canonical_path=fullfile(root,'results','data','stage7a','formal', ...
            'stage7a_comparison.csv');
        archived=readtable(canonical_path,'TextType','string');
        replay_id=stage4a4_scientific_config_hash(struct('role','archived_replay', ...
            'artifact_sha256',stage4a7_2_r2_sha256_file(canonical_path), ...
            'observation_seeds',sc.stage6b.seed+500000+(1:sc.stage6b.scale.replicates)));
    end
    replay_count=0;replay_max_distance_error=0;
    for q=1:numel(sc.stage6b.scale.grammars)
        grammar=sc.stage6b.scale.grammars(q);scenario=['scale_' grammar.scale_id];
        lib=stage6b_build_candidate_library('radial_grammar',grammar,base,struct());
        assert(any(strcmp(arrayfun(@(c)stage6b_network_signature(c.network), ...
            lib,'UniformOutput',false),truth_signature)), ...
            'stage7a1:TruthAbsent','Truth is missing from the %s library.',scenario);
        [baseline,baseline_t]=stage6b_calibrate_candidate_library(lib,base,sc.stage6b, ...
            scenario,q*100000);
        [original,original_t]=stage7a_calibrate_candidate_library(lib,base,sc, ...
            scenario,q*100000);
        cache=original.cache;models={original};model_names={'stage7a_original_reused'};
        model_timings={struct('set_time_s',original_t.calibration_time_s, ...
            'evidence_time_s',NaN)};
        original_set_id=stage4a4_scientific_config_hash(struct('role','stage7a_original', ...
            'tag',scenario,'seed',original.calibration_seed, ...
            'offset',original.calibration_seed_offset, ...
            'topology_calibration_hash',original.topology_model.calibration_hash));
        original_evidence_id=stage4a4_scientific_config_hash(struct('role','stage7a_reused_evidence', ...
            'tag',scenario,'set_id',original_set_id, ...
            'evidence_hash',original.evidence_model.calibration_hash));
        baseline_set_id=stage4a4_scientific_config_hash(struct('source','stage6b_original', ...
            'tag',scenario,'seed',sc.stage6b.seed,'offset',q*100000));
        resource_cells{end+1}=resource_row(scenario,'stage6b_baseline',baseline, ...
            baseline_t.cache_time_s,baseline_t.calibration_time_s,NaN, ...
            baseline.evidence_model.reference_sample_count,'calibrated'); %#ok<AGROW>
        identity_cells{end+1}=identity_row(scenario,'stage6b_baseline',baseline, ...
            baseline_set_id, ...
            baseline.evidence_model.calibration_hash,test_id,sc.stage6b.calibration_snr_db, ...
            sc.stage6b.calibration_per_candidate,sc.stage6b.parameter_search.main_length_scale, ...
            [1 1],sc.stage6b.seed+q*100000,sc.stage6b.seed+q*100000); %#ok<AGROW>
        for cix=1:numel(dc.conditions)
            cond=dc.conditions(cix);
            seed_a=dc.set_seed_base+cix*dc.condition_seed_stride+q*dc.library_seed_stride;
            seed_b=dc.evidence_seed_base+cix*dc.condition_seed_stride+q*dc.library_seed_stride;
            try
                [candidate,timing]=stage7a1_calibrate_split_library(lib,base,sc,cache, ...
                    cond,scenario,seed_a,seed_b);
                models{end+1}=candidate;model_names{end+1}=cond.name; %#ok<AGROW>
                model_timings{end+1}=timing; %#ok<AGROW>
            catch ME
                if strcmp(ME.identifier,'stage5b1:InsufficientReferenceCalibration')
                    models{end+1}=[];model_names{end+1}=cond.name; %#ok<AGROW>
                    model_timings{end+1}=struct('set_time_s',NaN,'evidence_time_s',NaN); %#ok<AGROW>
                    fprintf('  %s %s: insufficient independent evidence reference rows.\n', ...
                        scenario,cond.name);
                else,rethrow(ME);end
            end
        end
        cond=dc.conditions(strcmp({dc.conditions.name},'combined_broad35_n20'));
        seed_a=dc.set_seed_base+8*dc.condition_seed_stride+q*dc.library_seed_stride;
        seed_b=dc.evidence_seed_base+8*dc.condition_seed_stride+q*dc.library_seed_stride;
        try
            [candidate,timing]=stage7a1_calibrate_split_library(lib,base,sc,cache, ...
                cond,scenario,seed_a,seed_b,original);
            models{end+1}=candidate;model_names{end+1}='originalset_split_evidence_n20'; %#ok<AGROW>
            model_timings{end+1}=timing; %#ok<AGROW>
        catch ME
            if strcmp(ME.identifier,'stage5b1:InsufficientReferenceCalibration')
                models{end+1}=[];model_names{end+1}='originalset_split_evidence_n20'; %#ok<AGROW>
                model_timings{end+1}=struct('set_time_s',NaN,'evidence_time_s',NaN); %#ok<AGROW>
                fprintf('  %s originalset_split_evidence_n20: insufficient reference rows.\n',scenario);
            else,rethrow(ME);end
        end
        for k=1:numel(models)
            if isempty(models{k}),status='insufficient_reference';bytes=NaN;ref=0;sid='';eid='';
            else
                status='calibrated';bytes=model_bytes(models{k});
                ref=models{k}.evidence_model.reference_sample_count;
                if k==1,sid=original_set_id;eid=original_evidence_id;
                else,sid=models{k}.calibration_set_id;eid=models{k}.evidence_set_id;end
            end
            if k==1,cache_time=original_t.cache_time_s;else,cache_time=0;end
            resource_cells{end+1}=resource_row(scenario,model_names{k},models{k}, ...
                cache_time,model_timings{k}.set_time_s, ...
                model_timings{k}.evidence_time_s,ref,status,bytes); %#ok<AGROW>
            if k==1,cond_snr=sc.calibration_snr_db;cond_n=sc.calibration_per_candidate;
                cond_main=sc.search.main_scale_bounds;cond_load=sc.search.branch_load_scale_bounds;
                sa=sc.calibration_seed+sc.calibration_seed_offset+q*100000;sb=sa;
            elseif k==numel(models)
                cond_snr=cond.snr_db;cond_n=cond.per_candidate;
                cond_main=cond.main_bounds;cond_load=cond.load_bounds;
                sa=sc.calibration_seed+sc.calibration_seed_offset+q*100000;
                sb=seed_b;
            else
                condition=dc.conditions(k-1);cond_snr=condition.snr_db;
                cond_n=condition.per_candidate;cond_main=condition.main_bounds;
                cond_load=condition.load_bounds;
                sa=dc.set_seed_base+(k-1)*dc.condition_seed_stride+q*dc.library_seed_stride;
                sb=dc.evidence_seed_base+(k-1)*dc.condition_seed_stride+q*dc.library_seed_stride;
            end
            identity_cells{end+1}=identity_row(scenario,model_names{k},models{k}, ...
                sid,eid,test_id,cond_snr,cond_n,cond_main,cond_load,sa,sb,status); %#ok<AGROW>
        end
        if dc.canonical_replay
            for r=1:sc.stage6b.scale.replicates
                seed=sc.stage6b.seed+500000+r;
                [y,main_scale]=canonical_observation(truth,base,sc,seed);
                sample_id=sprintf('%s_r%02d',scenario,r);
                [old_score,new_score,profile]=score_pair(y,baseline,original,sc.search,truth);
                replay_max_distance_error=max(replay_max_distance_error, ...
                    verify_replay(archived,scenario,sample_id,'stage6b',old_score));
                replay_max_distance_error=max(replay_max_distance_error, ...
                    verify_replay(archived,scenario,sample_id,'stage7a',new_score));
                replay_count=replay_count+1;
                [sample_cells,candidate_cells]=record_observation(sample_cells,candidate_cells, ...
                    y,baseline,old_score.distance_vector,[],truth_signature, ...
                    'archived_replay',scenario,sample_id,'stage6b_baseline',seed,main_scale, ...
                    baseline_set_id,baseline.evidence_model.calibration_hash,replay_id);
                [sample_cells,candidate_cells]=record_observation(sample_cells,candidate_cells, ...
                    y,original,profile.profile_distances,profile,truth_signature, ...
                    'archived_replay',scenario,sample_id,'stage7a_original_reused',seed,main_scale, ...
                    original_set_id,original_evidence_id,replay_id);
                % These two previously identified small-library cases are
                % an explicitly exploratory readout under already fixed
                % diagnostic calibration models, never calibration inputs.
                if q==1&&(r==1||r==7)
                    for k=2:numel(models)
                        if isempty(models{k}),continue;end
                        [sample_cells,candidate_cells]=record_observation(sample_cells,candidate_cells, ...
                            y,models{k},profile.profile_distances,profile,truth_signature, ...
                            'archived_counterfactual',scenario,sample_id,model_names{k}, ...
                            seed,main_scale,models{k}.calibration_set_id, ...
                            models{k}.evidence_set_id,replay_id);
                    end
                end
                [search_cells,search_candidate_cells]=record_search(search_cells, ...
                    search_candidate_cells,y,baseline,original,profile,truth_signature, ...
                    'archived_replay',scenario,sample_id,seed,main_scale,sc.search);
            end
        end
        for r=1:dc.test_replicates
            y=test_y(r,:);seed=test_seed(r);main_scale=test_main(r);
            sample_id=sprintf('diagnostic_r%03d',r);
            old_score=stage6b_evaluate_observation(y,baseline,truth);
            [sample_cells,candidate_cells]=record_observation(sample_cells,candidate_cells, ...
                y,baseline,old_score.distance_vector,[],truth_signature, ...
                'independent_test',scenario,sample_id,'stage6b_baseline',seed,main_scale, ...
                baseline_set_id, ...
                baseline.evidence_model.calibration_hash,test_id);
            profile=stage7a_profile_distance(y,cache,sc.search);
            for k=1:numel(models)
                if isempty(models{k}),continue;end
                if k==1,sid=original_set_id;eid=original_evidence_id;
                else,sid=models{k}.calibration_set_id;eid=models{k}.evidence_set_id;end
                [sample_cells,candidate_cells]=record_observation(sample_cells,candidate_cells, ...
                    y,models{k},profile.profile_distances,profile,truth_signature, ...
                    'independent_test',scenario,sample_id,model_names{k},seed,main_scale, ...
                    sid,eid,test_id);
                if r==1
                    direct=stage7a_score_observation(y,models{k},sc.search);
                    assert(strcmp(sample_cells{end}.decision_state,direct.decision_state)&& ...
                        abs(sample_cells{end}.d1-direct.distance)<1e-12, ...
                        'stage7a1:AuditScoreMismatch','Diagnostic decision differs from Stage 7A score API.');
                end
            end
            [search_cells,search_candidate_cells]=record_search(search_cells, ...
                search_candidate_cells,y,baseline,original,profile,truth_signature, ...
                'independent_test',scenario,sample_id,seed,main_scale,sc.search);
        end
        fprintf('  %s: %d candidate models, %d independent test observations.\n', ...
            scenario,numel(lib),dc.test_replicates);
    end
    samples=vertcat(sample_cells{:});candidate_rows=vertcat(candidate_cells{:});
    search_rows=vertcat(search_cells{:});search_candidate_rows=vertcat(search_candidate_cells{:});
    resources=vertcat(resource_cells{:});identities=vertcat(identity_cells{:});
    summary=group_summary(samples);
    writetable(struct2table(samples),fullfile(out,'stage7a1_sample_diagnostics.csv'));
    writetable(struct2table(candidate_rows),fullfile(out,'stage7a1_candidate_diagnostics.csv'));
    writetable(struct2table(search_rows),fullfile(out,'stage7a1_search_audit.csv'));
    writetable(struct2table(search_candidate_rows),fullfile(out,'stage7a1_search_candidate_audit.csv'));
    writetable(struct2table(summary),fullfile(out,'stage7a1_group_summary.csv'));
    writetable(struct2table(resources),fullfile(out,'stage7a1_resource_cost.csv'));
    writetable(struct2table(identities),fullfile(out,'stage7a1_calibration_identity.csv'));
    snapshot=dc;snapshot.output_root=['results/data/stage7a_1/' mode];
    snapshot.log_root='results/logs/stage7a_1';
    snapshot.stage7a.output_root='results/data/stage7a';
    snapshot.stage7a.log_root='results/logs/stage7a';
    snapshot.stage7a.stage6b.output_root='results/data/stage6b';
    snapshot.stage7a.stage6b.figure_root='results/figures/stage6b';
    snapshot.stage7a.stage6b.identifiability.stage5b1_model_file= ...
        'results/data/stage5b1/formal/stage5b1_results.mat';
    save(fullfile(out,'stage7a1_config_snapshot.mat'),'snapshot','-v7');
    meta=table(string({'source_commit';'stage7a_algorithm_commit';'mode';'matlab_version'; ...
        'computer_arch';'protocol_hash';'test_set_id';'test_seed_base';'set_seed_base'; ...
        'evidence_seed_base';'test_replicates_per_library';'canonical_replay_samples'; ...
        'canonical_replay_max_distance_error';'use_parallel';'worker_count';'runtime_s'; ...
        'verification_time_utc'}), ...
        string({dc.source_commit;dc.stage7a_algorithm_commit;mode;version;computer('arch'); ...
        stage4a4_scientific_config_hash(snapshot);test_id;num2str(dc.test_seed_base); ...
        num2str(dc.set_seed_base);num2str(dc.evidence_seed_base); ...
        num2str(dc.test_replicates);num2str(replay_count); ...
        num2str(replay_max_distance_error,17);'0';'0';num2str(toc(started),17); ...
        char(datetime('now','TimeZone','UTC','Format','yyyy-MM-dd HH:mm:ss'))}), ...
        'VariableNames',{'key','value'});
    writetable(meta,fullfile(out,'stage7a1_metadata.csv'));
    result=struct('stage','Stage 7A.1','mode',mode,'status','completed', ...
        'sample_rows',numel(samples),'candidate_rows',numel(candidate_rows), ...
        'search_rows',numel(search_rows),'replay_count',replay_count, ...
        'replay_max_distance_error',replay_max_distance_error, ...
        'test_set_id',test_id,'elapsed_s',toc(started));
    fprintf('Stage 7A.1 %s: %d samples, %d candidate rows, %d replay matches, %.3f s.\n', ...
        mode,result.sample_rows,result.candidate_rows,replay_count,result.elapsed_s);
end

function [y,main,seeds]=new_test_observations(truth,base,dc)
    n=dc.test_replicates;sc=dc.stage7a;y=complex(zeros(n,numel(sc.frequency_hz)));
    main=zeros(n,1);seeds=zeros(n,1);
    for r=1:n
        seeds(r)=dc.test_seed_base+r;rs=RandStream('mt19937ar','Seed',seeds(r));
        main(r)=dc.test_main_bounds(1)+diff(dc.test_main_bounds)*rand(rs);
        theta=nominal_theta(sc);theta.main_length_scale=main(r);
        clean=stage6b_forward_cfr(truth,theta,base,sc.frequency_hz,sc.measurement_kind);
        y(r,:)=add_noise(clean,dc.test_snr_db,rs);
    end
end
function [y,main]=canonical_observation(truth,base,sc,seed)
    rs=RandStream('mt19937ar','Seed',seed);
    v=sc.stage6b.parameter_search.main_length_scale;
    main=min(v)+(max(v)-min(v))*rand(rs);theta=nominal_theta(sc);
    theta.main_length_scale=main;
    clean=stage6b_forward_cfr(truth,theta,base,sc.frequency_hz,sc.measurement_kind);
    y=add_noise(clean,sc.stage6b.scale.snr_db,rs);
end
function theta=nominal_theta(sc)
    theta=struct('main_length_scale',1,'branch_length_scale',1,'branch_load_scale',1, ...
        'source_impedance_ohm',sc.search.source_impedance_ohm, ...
        'receiver_impedance_ohm',sc.search.receiver_impedance_ohm,'regularization',0);
end
function y=add_noise(x,snr,rs)
    s=sqrt(mean(abs(x).^2)/10^(snr/10)/2);
    y=x+s*(randn(rs,size(x))+1i*randn(rs,size(x)));
end
function truth=truth_network(lib,nodes)
    ix=find(arrayfun(@(x)isequal(sort([x.network.branches.node]),sort(nodes)),lib),1);
    assert(~isempty(ix),'stage7a1:TruthAbsent','Controlled truth is absent from reference library.');
    truth=lib(ix).network;
end
function [old_score,new_score,profile]=score_pair(y,baseline,original,search,truth)
    old_score=stage6b_evaluate_observation(y,baseline,truth);
    new_score=stage7a_score_observation(y,original,search);
    profile=stage7a_profile_distance(y,original.cache,search);
    assert(max(abs(profile.profile_distances-new_score.distance_vector))<1e-12, ...
        'stage7a1:ProfileMismatch','Cached profile does not match production scorer.');
end
function error_value=verify_replay(archived,scenario,sample_id,method,score)
    ix=find(archived.scenario==string(scenario)&archived.sample==string(sample_id)& ...
        archived.method==string(method));
    assert(numel(ix)==1,'stage7a1:ArchivedRowMissing','Missing or duplicate Stage 7A archived row.');
    error_value=abs(score.distance-archived.distance(ix));
    assert(error_value<=1e-12&&strcmp(score.decision_state,char(archived.decision_state(ix)))&& ...
        score.candidate_set_size==archived.candidate_set_size(ix), ...
        'stage7a1:ArchivedReplayMismatch','Archived score differs for %s %s.',scenario,sample_id);
end
function [samples,candidates]=record_observation(samples,candidates,y,model,d,profile,truth_signature, ...
        dataset,scenario,sample_id,method,seed,main_scale,set_id,evidence_id,test_id)
    started=tic;[s,c]=stage7a1_audit_decision(y,model,d,truth_signature,profile);
    s.dataset=dataset;s.scenario=scenario;s.sample=sample_id;s.method=method;
    s.observation_seed=seed;s.truth_main_scale=main_scale;s.truth_load_scale=1;
    s.calibration_set_id=set_id;s.evidence_set_id=evidence_id;s.test_set_id=test_id;
    s.audit_time_s=toc(started);samples{end+1}=s; %#ok<AGROW>
    for k=1:numel(c)
        c(k).dataset=dataset;c(k).scenario=scenario;c(k).sample=sample_id;
        c(k).method=method;c(k).observation_seed=seed;
        c(k).calibration_set_id=set_id;c(k).evidence_set_id=evidence_id;
        c(k).test_set_id=test_id;
    end
    candidates{end+1}=c; %#ok<AGROW>
end
function [rows,candidate_rows]=record_search(rows,candidate_rows,y,baseline,model,coarse,truth_signature, ...
        dataset,scenario,sample_id,seed,true_main_scale,search)
    exhaustive=stage7a1_exhaustive_profile_distance(y,model.cache,search);
    baseline_profile=stage4a7_2_r1_profile_distance({y},baseline.cache, ...
        struct('feature','complex_raw'));
    assert(isequal(baseline.candidate_ids,model.candidate_ids), ...
        'stage7a1:SearchAuditLibraryMismatch','Baseline and Stage 7A candidate order differs.');
    [a,~]=stage7a1_audit_decision(y,model,coarse.profile_distances,truth_signature,coarse);
    [b,~]=stage7a1_audit_decision(y,model,exhaustive.profile_distances,truth_signature,exhaustive);
    delta=coarse.profile_distances-exhaustive.profile_distances;
    assert(all(delta>=-1e-12),'stage7a1:ExhaustiveExceededCoarse', ...
        'Exhaustive cached fine grid cannot exceed a local minimum.');
    truth_ix=a.truth_index;truth_error=NaN;if isfinite(truth_ix),truth_error=delta(truth_ix);end
    baseline_theta=baseline_profile.best_theta{truth_ix};
    row=struct('dataset',dataset,'scenario',scenario,'sample',sample_id, ...
        'observation_seed',seed,'candidate_count',numel(model.candidate_ids), ...
        'true_main_scale_audit_only',true_main_scale, ...
        'baseline_truth_distance',baseline_profile.profile_distances(truth_ix), ...
        'baseline_truth_best_main_scale',baseline_theta.main_length_scale, ...
        'baseline_truth_best_load_scale',baseline_theta.branch_load_scale, ...
        'stage7a_coarse_truth_distance',coarse.profile_distances(truth_ix), ...
        'stage7a_coarse_truth_best_main_scale',coarse.best_main_scale(truth_ix), ...
        'stage7a_coarse_truth_best_load_scale',coarse.best_branch_load_scale(truth_ix), ...
        'stage7a_exhaustive_truth_distance',exhaustive.profile_distances(truth_ix), ...
        'stage7a_exhaustive_truth_best_main_scale',exhaustive.best_main_scale(truth_ix), ...
        'stage7a_exhaustive_truth_best_load_scale',exhaustive.best_branch_load_scale(truth_ix), ...
        'exhaustive_minus_baseline_truth_distance', ...
            exhaustive.profile_distances(truth_ix)-baseline_profile.profile_distances(truth_ix), ...
        'max_distance_error',max(abs(delta)),'truth_distance_error',truth_error, ...
        'top1_changed',~strcmp(a.best_candidate,b.best_candidate), ...
        'candidate_set_changed',~strcmp(a.candidate_set,b.candidate_set), ...
        'state_changed',~strcmp(a.decision_state,b.decision_state), ...
        'coarse_state',a.decision_state,'exhaustive_state',b.decision_state, ...
        'coarse_set',a.candidate_set,'exhaustive_set',b.candidate_set, ...
        'global_outside_local_count',nnz(~exhaustive.global_in_local_window), ...
        'coarse_template_comparisons',coarse.template_comparisons, ...
        'exhaustive_template_comparisons',exhaustive.template_comparisons, ...
        'exhaustive_runtime_s',exhaustive.runtime_s);
    rows{end+1}=row; %#ok<AGROW>
    c=repmat(struct('dataset',dataset,'scenario',scenario,'sample',sample_id, ...
        'candidate_id','','coarse_distance',NaN,'exhaustive_distance',NaN, ...
        'distance_error',NaN,'coarse_best_template_index',NaN, ...
        'exhaustive_best_template_index',NaN,'coarse_pivot_index',NaN, ...
        'global_in_local_window',false,'coarse_pivot_distance',NaN), ...
        numel(model.candidate_ids),1);
    for k=1:numel(c)
        c(k).candidate_id=model.candidate_ids{k};
        c(k).coarse_distance=coarse.profile_distances(k);
        c(k).exhaustive_distance=exhaustive.profile_distances(k);
        c(k).distance_error=delta(k);
        c(k).coarse_best_template_index=coarse.best_template_indices(k);
        c(k).exhaustive_best_template_index=exhaustive.best_template_indices(k);
        c(k).coarse_pivot_index=exhaustive.coarse_pivot_indices(k);
        c(k).global_in_local_window=exhaustive.global_in_local_window(k);
        c(k).coarse_pivot_distance=exhaustive.coarse_pivot_distance(k);
    end
    candidate_rows{end+1}=c; %#ok<AGROW>
end
