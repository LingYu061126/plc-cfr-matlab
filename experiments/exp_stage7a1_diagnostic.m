function r=identity_row(scenario,condition,model,set_id,evidence_id,test_id,snr,n,main,load,seed_a,seed_b,status)
    if nargin<13,status='calibrated';end
    if isempty(model),ids='';library_hash='';search_hash='';beta=NaN;
        margin=NaN;conf=NaN;entropy=NaN;domain=NaN;
        self_coverage=NaN;independent_coverage=NaN;independent_empty=NaN;
        independent_singleton=NaN;
    else
        ids=strjoin(model.candidate_ids,',');
        if isfield(model,'candidate_library_hash'),library_hash=model.candidate_library_hash;
        else
            signatures=arrayfun(@(c)stage6b_network_signature(c.network), ...
                model.candidates,'UniformOutput',false);
            library_hash=stage4a4_scientific_config_hash(struct( ...
                'ids',{model.candidate_ids},'signatures',{signatures}));
        end
        if isfield(model,'search_domain_hash'),search_hash=model.search_domain_hash;
        else,search_hash='stage6b_fixed_grid';end
        beta=model.evidence_model.beta;
        margin=model.evidence_model.margin_threshold;
        conf=model.evidence_model.top1_confidence_threshold;
        entropy=model.evidence_model.normalized_entropy_threshold;
        domain=model.domain_threshold;
        if isfield(model,'set_in_sample_truth_coverage')
            self_coverage=model.set_in_sample_truth_coverage;
            independent_coverage=model.evidence_out_of_sample_truth_coverage;
            independent_empty=model.evidence_out_of_sample_empty_count;
            independent_singleton=model.evidence_out_of_sample_singleton_count;
        else
            self_in_set=false(size(model.calibration_truth_index));
            for row_index=1:numel(self_in_set)
                accepted=stage4a7_2_r1_apply_profile_candidate_set( ...
                    model.calibration_distances(row_index,:),model.topology_model,'absolute');
                self_in_set(row_index)=any(strcmp(accepted.accepted_candidate_set, ...
                    model.candidate_ids{model.calibration_truth_index(row_index)}));
            end
            self_coverage=mean(self_in_set);
            independent_coverage=NaN;independent_empty=NaN;independent_singleton=NaN;
        end
    end
    r=struct('scenario',scenario,'condition',condition,'status',status, ...
        'candidate_order',ids,'candidate_library_hash',library_hash, ...
        'search_domain_hash',search_hash,'calibration_set_id',set_id, ...
        'evidence_set_id',evidence_id,'test_set_id',test_id, ...
        'calibration_snr_db',snr,'per_candidate',n, ...
        'calibration_main_bounds',mat2str(main), ...
        'calibration_load_bounds',mat2str(load), ...
        'set_seed_base',seed_a,'evidence_seed_base',seed_b, ...
        'set_in_sample_truth_coverage',self_coverage, ...
        'evidence_out_of_sample_truth_coverage',independent_coverage, ...
        'evidence_out_of_sample_empty_count',independent_empty, ...
        'evidence_out_of_sample_singleton_count',independent_singleton, ...
        'domain_threshold',domain,'beta',beta,'margin_threshold',margin, ...
        'confidence_threshold',conf,'entropy_threshold',entropy);
end
function summary=group_summary(rows)
    keys=unique(strcat(string({rows.dataset}),"|",string({rows.scenario}),"|", ...
        string({rows.method})),'stable');
    summary=repmat(struct('dataset','','scenario','','method','','n',0, ...
        'best_truth_k',0,'correct_unique_k',0,'false_unique_k',0, ...
        'truth_set_coverage_k',0,'domain_rejected_k',0,'empty_set_k',0, ...
        'unique_k',0,'ambiguous_k',0,'low_confidence_k',0,'rejected_k',0, ...
        'mean_candidate_set_size',NaN,'correct_unique_wilson_low',NaN, ...
        'correct_unique_wilson_high',NaN,'set_coverage_wilson_low',NaN, ...
        'set_coverage_wilson_high',NaN,'false_unique_wilson_low',NaN, ...
        'false_unique_wilson_high',NaN,'mean_audit_time_s',NaN),numel(keys),1);
    for k=1:numel(keys)
        parts=split(keys(k),'|');idx=strcmp({rows.dataset},char(parts(1)))& ...
            strcmp({rows.scenario},char(parts(2)))&strcmp({rows.method},char(parts(3)));
        x=rows(idx);n=numel(x);states={x.decision_state};
        u=nnz([x.correct_unique]);set_k=nnz([x.truth_in_candidate_set]);
        f=nnz([x.false_unique]);[ul,uh]=wilson(u,n);[sl,sh]=wilson(set_k,n);
        [fl,fh]=wilson(f,n);
        summary(k)=struct('dataset',char(parts(1)),'scenario',char(parts(2)), ...
            'method',char(parts(3)),'n',n,'best_truth_k',nnz([x.best_is_truth]), ...
            'correct_unique_k',u,'false_unique_k',f, ...
            'truth_set_coverage_k',set_k,'domain_rejected_k',nnz(~[x.domain_pass]), ...
            'empty_set_k',nnz([x.candidate_set_empty]), ...
            'unique_k',nnz(strcmp(states,'UNIQUE_CONFIDENT')), ...
            'ambiguous_k',nnz(strcmp(states,'MULTIPLE_AMBIGUOUS')), ...
            'low_confidence_k',nnz(strcmp(states,'LOW_CONFIDENCE')), ...
            'rejected_k',nnz(strcmp(states,'REJECTED')), ...
            'mean_candidate_set_size',mean([x.candidate_set_size]), ...
            'correct_unique_wilson_low',ul,'correct_unique_wilson_high',uh, ...
            'set_coverage_wilson_low',sl,'set_coverage_wilson_high',sh, ...
            'false_unique_wilson_low',fl,'false_unique_wilson_high',fh, ...
            'mean_audit_time_s',mean([x.audit_time_s]));
    end
end
function [lo,hi]=wilson(k,n)
    z=1.959963984540054;p=k/n;den=1+z^2/n;
    center=(p+z^2/(2*n))/den;
    radius=z*sqrt(p*(1-p)/n+z^2/(4*n^2))/den;
    lo=max(0,center-radius);hi=min(1,center+radius);
end
