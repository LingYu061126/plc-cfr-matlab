function out=exp_stage7a8_study(root,mode)
%EXP_STAGE7A8_STUDY Paired, serial C37 H50+Zin50 compute-only audit.
%   Truth and seeds are used only in simulation and retrospective tables.
    if nargin<1||isempty(root),root=fileparts(fileparts(mfilename('fullpath')));end
    if nargin<2||isempty(mode),mode='smoke';end
    addpath(fullfile(root,'src'),fullfile(root,'config'));
    base=default_config(root);cfg=stage7a8_config(base,mode);
    if ~exist(cfg.output_dir,'dir'),mkdir(cfg.output_dir);end
    if ~exist(cfg.log_dir,'dir'),mkdir(cfg.log_dir);end
    full_start=tic;setup_start=tic;
    [pool,base_ix,grammar,catalog,groups]=stage7a7_candidate_space(base,cfg);
    bank=stage7a5_template_bank(pool,base,cfg);
    setup_s=toc(setup_start);assert(numel(pool)==37);
    split_start=tic;
    E=stage7a5_generate_split(catalog,groups.inlib,base,cfg, ...
        cfg.seed_E,cfg.n_E_per_class,'E',false);
    sigma=estimate_sigma(E);
    A=stage7a5_generate_split(catalog,groups.inlib,base,cfg, ...
        cfg.seed_A,cfg.n_A_per_class,'A',false);
    F=stage7a5_generate_split(catalog,groups.inlib,base,cfg, ...
        cfg.seed_F,cfg.n_F_per_class,'F',false);
    testcfg=cfg;testcfg.true_main_bounds=cfg.test_main_bounds;
    T=[stage7a5_generate_split(catalog,groups.inlib,base,testcfg, ...
        cfg.seed_T_inlib,cfg.n_T_inlib_per_topology,'T_inlib',false); ...
       stage7a5_generate_split(catalog,groups.old_out,base,testcfg, ...
        cfg.seed_T_old_out,cfg.n_T_old_out_per_topology,'T_old_out',false); ...
       stage7a5_generate_split(catalog,groups.reachable,base,testcfg, ...
        cfg.seed_T_reachable,cfg.n_T_reachable_per_topology,'T_reachable',false); ...
       stage7a5_generate_split(catalog,groups.grammar_out,base,testcfg, ...
        cfg.seed_T_grammar_out,cfg.n_T_grammar_out_per_topology,'T_grammar_out',false); ...
       stage7a5_generate_split(catalog,groups.domain,base,testcfg, ...
        cfg.seed_T_domain,cfg.n_T_domain_per_topology,'T_domain',true)];
    split_s=toc(split_start);assert_unique_seeds(E,A,F,T);
    views=[1 2];budget=37;cal_start=tic;
    delta=zeros(numel(A),1);fit=zeros(numel(F),1);
    for i=1:numel(A)
        z=stage7a7_score_observation(A(i).observed,pool,bank,base, ...
            cfg,base_ix,views,sigma,budget,[]);
        j=find(strcmp(z.candidate_ids,A(i).truth_id),1);
        assert(~isempty(j),'stage7a8:CalibrationTruthMissing');
        delta(i)=z.distances(j)-min(z.distances);
    end
    for i=1:numel(F)
        z=stage7a7_score_observation(F(i).observed,pool,bank,base, ...
            cfg,base_ix,views,sigma,budget,[]);
        fit(i)=z.fit_statistic;
    end
    model=stage7a5_calibrate_split(delta,fit,bank,cfg, ...
        1:budget,views,sigma,'C',budget);
    model.condition_identity=stage7a7_condition_identity( ...
        cfg,bank,views,sigma,'C37',budget);
    calibration_s=toc(cal_start);
    calibration=table(string(bank.identity),string(bank.search_identity), ...
        string(model.calibration_identity),string(model.condition_identity), ...
        sigma(1),sigma(2),model.set_threshold,model.fit_threshold, ...
        numel(E),numel(A),numel(F), ...
        'VariableNames',{'bank_identity','search_identity', ...
        'calibration_identity','condition_identity','sigma_h', ...
        'sigma_zin','set_threshold','fit_threshold','E_n','A_n','F_n'});
    writetable(calibration,fullfile(cfg.output_dir,'calibration.csv'));
    arch_ok=true;
    if strcmp(mode,'formal')
        archived=readtable(fullfile(root,'results','data','stage7a_7', ...
            'formal','nominal','calibration.csv'),'TextType','string');
        ix=archived.scheme=="H50_Zin50"&archived.flow=="C37";
        assert(sum(ix)==1,'stage7a8:ArchivedCalibrationMissing');
        a=archived(ix,:);
        arch_ok=strcmp(a.bank_identity,bank.identity)&& ...
            strcmp(a.search_identity,bank.search_identity)&& ...
            strcmp(a.calibration_identity,model.calibration_identity)&& ...
            strcmp(a.condition_identity,model.condition_identity)&& ...
            abs(a.sigma_h-sigma(1))<1e-10&& ...
            abs(a.sigma_zin-sigma(2))<1e-10&& ...
            abs(a.set_threshold-model.set_threshold)<1e-10&& ...
            abs(a.fit_threshold-model.fit_threshold)<1e-10;
        assert(arch_ok,'stage7a8:ArchivedCalibrationMismatch');
    end
    sample_rows=repmat(sample_row(),2*numel(T),1);
    candidate_rows=repmat(candidate_row(),2*numel(T)*budget,1);
    comparison_rows=repmat(comparison_row(),numel(T),1);cursor=0;
    test_start=tic;
    for i=1:numel(T)
        s=T(i);id=sprintf('%s_%s_%03d',s.split,s.truth_id,s.replicate);
        if mod(i,2)==1,sequence={'A','B'};else,sequence={'B','A'};end
        scores=cell(1,2);decisions=cell(1,2);seconds=zeros(1,2);
        for p=1:2
            method=sequence{p};t=tic;
            if strcmp(method,'A')
                z=stage7a7_score_observation(s.observed,pool,bank,base, ...
                    cfg,base_ix,views,sigma,budget,model);j=1;
            else
                z=stage7a8_score_observation(s.observed,pool,bank,base, ...
                    cfg,base_ix,views,sigma,model);j=2;
            end
            decision=stage7a5_decide(z,model,bank);
            seconds(j)=toc(t);scores{j}=z;decisions{j}=decision;
            sample_rows(2*i-2+j)=make_sample_row(id,s,z,decision, ...
                method,seconds(j));
            [~,order]=sortrows([z.distances(:),(1:budget).'],[1 2]);
            for k=1:budget
                cursor=cursor+1;candidate_rows(cursor)=make_candidate_row( ...
                    id,s,method,z,decision,bank,k,find(order==k,1));
            end
        end
        comparison_rows(i)=compare_one(id,s,scores{1},scores{2}, ...
            decisions{1},decisions{2},seconds);
        if mod(i,10)==0||i==numel(T)
            fprintf('Stage 7A.8 %s paired %d/%d, elapsed %.3f s\n', ...
                mode,i,numel(T),toc(test_start));
        end
    end
    test_s=toc(test_start);
    candidate_rows=candidate_rows(1:cursor);
    samples=struct2table(sample_rows);candidates=struct2table(candidate_rows);
    comparisons=struct2table(comparison_rows);
    writetable(samples,fullfile(cfg.output_dir,'samples.csv'));
    writetable(candidates,fullfile(cfg.output_dir,'candidate_audit.csv'));
    writetable(comparisons,fullfile(cfg.output_dir,'paired_comparison.csv'));
    summary=make_summary(samples);writetable(summary, ...
        fullfile(cfg.output_dir,'summary.csv'));
    archived_samples_match=true;
    if strcmp(mode,'formal')
        archived_samples_match=check_archived_samples(root,samples);
    end
    total_s=toc(full_start);peak_kb=process_peak_rss_kb();
    meta=table(string(cfg.verification_baseline_commit),string(version), ...
        string(computer('arch')),string(mode),string(bank.identity), ...
        string(bank.search_identity),string(model.calibration_identity), ...
        numel(T),budget,bank.forward_calls,bank.build_time_s, ...
        bank.logical_cache_bytes,setup_s,split_s,calibration_s,test_s, ...
        total_s,peak_kb,cfg.use_parallel,cfg.worker_count,arch_ok, ...
        archived_samples_match,string(datetime('now','TimeZone','UTC', ...
        'Format','yyyy-MM-dd HH:mm:ss')), ...
        'VariableNames',{'baseline_commit','matlab_version','computer_arch', ...
        'mode','bank_identity','search_identity','calibration_identity', ...
        'test_observations','candidate_count','template_forward_calls', ...
        'template_build_s','template_cache_bytes','setup_s','split_s', ...
        'calibration_s','test_scoring_s','total_s','process_peak_rss_kb', ...
        'use_parallel','worker_count','archived_calibration_match', ...
        'archived_baseline_samples_match','verification_time_utc'});
    writetable(meta,fullfile(cfg.output_dir,'metadata.csv'));
    save(fullfile(cfg.output_dir,'config_snapshot.mat'), ...
        'cfg','grammar','groups','sigma','model','meta','-v7');
    assert(all(comparisons.equivalent),'stage7a8:PairedDifference');
    assert(archived_samples_match,'stage7a8:ArchivedBaselineMismatch');
    fprintf('Stage 7A.8 %s PASS: %d pairs, total %.3f s, peak %.0f kB\n', ...
        mode,numel(T),total_s,peak_kb);
    out=struct('output_dir',cfg.output_dir,'runtime_s',total_s, ...
        'all_equivalent',all(comparisons.equivalent),'summary',summary);
end

function sigma=estimate_sigma(samples)
    squared=zeros(1,2);
    for i=1:numel(samples)
        for v=1:2
            squared(v)=squared(v)+mean(abs(samples(i).observed{v}- ...
                samples(i).clean{v}).^2);
        end
    end
    sigma=sqrt(squared/numel(samples));
end
function assert_unique_seeds(E,A,F,T)
    all=[E;A;F;T];p=[all.parameter_seed];n=[all.noise_seed];
    assert(numel(unique(p))==numel(p)&&numel(unique(n))==numel(n)&& ...
        isempty(intersect(p,n)),'stage7a8:SeedOverlap');
end
function r=sample_row()
    r=struct('sample_id','','split','','scenario','','method','', ...
        'truth_id','','truth_signature','','parameter_seed',0, ...
        'noise_seed',0,'truth_in_pool',false,'domain_out',false, ...
        'candidate_count',0,'optimizer_evaluations',0,'wall_clock_s',NaN, ...
        'best_candidate','','truth_rank',0,'truth_in_set',false, ...
        'candidate_set','','set_size',0,'distance_1',NaN, ...
        'distance_2',NaN,'margin',NaN,'fit_statistic',NaN, ...
        'fit_threshold',NaN,'state','','reason','', ...
        'correct_unique',false,'false_unique',false);
end
function r=make_sample_row(id,s,z,d,method,seconds)
    [~,order]=sortrows([z.distances(:),(1:numel(z.distances)).'],[1 2]);
    truth=find(strcmp(z.candidate_ids,s.truth_id),1);
    r=sample_row();r.sample_id=id;r.split=s.split;r.scenario=s.scenario;
    r.method=method;r.truth_id=s.truth_id;r.truth_signature=s.truth_signature;
    r.parameter_seed=s.parameter_seed;r.noise_seed=s.noise_seed;
    r.truth_in_pool=~isempty(truth);r.domain_out=s.domain_out;
    r.candidate_count=numel(z.candidate_ids);
    r.optimizer_evaluations=z.optimizer_evaluations;r.wall_clock_s=seconds;
    r.best_candidate=d.best_candidate;
    if ~isempty(truth),r.truth_rank=find(order==truth,1);end
    r.truth_in_set=any(strcmp(d.candidate_set,s.truth_id));
    r.candidate_set=strjoin(d.candidate_set,';');r.set_size=d.candidate_set_size;
    r.distance_1=d.distance_1;r.distance_2=d.distance_2;
    r.margin=d.margin;r.fit_statistic=d.fit_statistic;
    r.fit_threshold=d.fit_threshold;r.state=d.decision_state;
    r.reason=d.decision_reason;
    r.correct_unique=strcmp(r.state,'UNIQUE_CONFIDENT')&& ...
        strcmp(r.best_candidate,s.truth_id);
    r.false_unique=strcmp(r.state,'UNIQUE_CONFIDENT')&& ...
        ~strcmp(r.best_candidate,s.truth_id);
end
function r=candidate_row()
    r=struct('sample_id','','split','','scenario','','method','', ...
        'truth_id','','candidate_id','','signature','','rank',0, ...
        'distance',NaN,'grid_distance',NaN,'fit_main_scale',NaN, ...
        'fit_load_scale',NaN,'truth_candidate',false, ...
        'in_candidate_set',false);
end
function r=make_candidate_row(id,s,method,z,d,bank,k,rank)
    r=candidate_row();r.sample_id=id;r.split=s.split;r.scenario=s.scenario;
    r.method=method;r.truth_id=s.truth_id;r.candidate_id=z.candidate_ids{k};
    r.signature=bank.candidate_signatures{k};r.rank=rank;
    r.distance=z.distances(k);r.grid_distance=z.grid_distances(k);
    r.fit_main_scale=z.params(k,1);r.fit_load_scale=z.params(k,2);
    r.truth_candidate=strcmp(r.candidate_id,s.truth_id);
    r.in_candidate_set=any(strcmp(d.candidate_set,r.candidate_id));
end
function r=comparison_row()
    r=struct('sample_id','','split','','scenario','', ...
        'candidate_ids_match',false,'rank_match',false, ...
        'set_match',false,'state_match',false,'best_match',false, ...
        'reason_match',false,'distance_match',false, ...
        'parameter_match',false,'fit_match',false, ...
        'optimizer_evaluations_match',false,'max_distance_error',NaN, ...
        'max_parameter_error',NaN,'fit_error',NaN, ...
        'a_seconds',NaN,'b_seconds',NaN,'speedup',NaN, ...
        'equivalent',false);
end
function r=compare_one(id,s,a,b,da,db,seconds)
    r=comparison_row();r.sample_id=id;r.split=s.split;r.scenario=s.scenario;
    r.candidate_ids_match=isequal(a.candidate_ids,b.candidate_ids);
    [~,ra]=sortrows([a.distances(:),(1:numel(a.distances)).'],[1 2]);
    [~,rb]=sortrows([b.distances(:),(1:numel(b.distances)).'],[1 2]);
    r.rank_match=isequal(ra,rb);r.set_match=isequal(da.candidate_set,db.candidate_set);
    r.state_match=strcmp(da.decision_state,db.decision_state);
    r.best_match=strcmp(da.best_candidate,db.best_candidate);
    r.reason_match=strcmp(da.decision_reason,db.decision_reason);
    r.max_distance_error=max(abs(a.distances-b.distances));
    r.max_parameter_error=max(abs(a.params(:)-b.params(:)));
    r.fit_error=abs(a.fit_statistic-b.fit_statistic);
    r.distance_match=all(abs(a.distances-b.distances)<= ...
        1e-9+1e-10*abs(a.distances));
    r.parameter_match=r.max_parameter_error<=1e-6;
    r.fit_match=r.fit_error<=1e-9+1e-10*abs(a.fit_statistic);
    r.optimizer_evaluations_match=a.optimizer_evaluations==b.optimizer_evaluations;
    r.a_seconds=seconds(1);r.b_seconds=seconds(2);
    r.speedup=seconds(1)/seconds(2);
    r.equivalent=all([r.candidate_ids_match r.rank_match r.set_match, ...
        r.state_match r.best_match r.reason_match r.distance_match, ...
        r.parameter_match r.fit_match r.optimizer_evaluations_match]);
end
function summary=make_summary(samples)
    splits=unique(samples.split,'stable');methods=["A";"B"];
    rows=repmat(struct('split','','method','','n',0,'correct_unique_k',0, ...
        'false_unique_k',0,'rejected_k',0,'ambiguous_k',0, ...
        'low_confidence_k',0,'truth_in_set_k',0,'mean_set_size',NaN, ...
        'total_scoring_s',NaN,'mean_scoring_s',NaN, ...
        'median_scoring_s',NaN),numel(splits)*2,1);j=0;
    for a=1:numel(splits)
        for b=1:2
            j=j+1;ix=strcmp(samples.split,splits{a})& ...
                strcmp(samples.method,methods(b));x=samples(ix,:);
            rows(j)=struct('split',splits{a},'method',char(methods(b)), ...
                'n',height(x),'correct_unique_k',sum(x.correct_unique), ...
                'false_unique_k',sum(x.false_unique), ...
                'rejected_k',sum(strcmp(x.state,'REJECTED')), ...
                'ambiguous_k',sum(strcmp(x.state,'MULTIPLE_AMBIGUOUS')), ...
                'low_confidence_k',sum(strcmp(x.state,'LOW_CONFIDENCE')), ...
                'truth_in_set_k',sum(x.truth_in_set), ...
                'mean_set_size',mean(x.set_size), ...
                'total_scoring_s',sum(x.wall_clock_s), ...
                'mean_scoring_s',mean(x.wall_clock_s), ...
                'median_scoring_s',median(x.wall_clock_s));
        end
    end
    summary=struct2table(rows);
end
function passed=check_archived_samples(root,samples)
    archived=readtable(fullfile(root,'results','data','stage7a_7', ...
        'formal','nominal','samples.csv'),'TextType','string');
    ix=archived.scheme=="H50_Zin50"&archived.flow=="C37";
    old=archived(ix,:);fresh=samples(strcmp(samples.method,'A'),:);
    passed=height(old)==height(fresh);
    for i=1:height(fresh)
        j=find(old.sample_id==string(fresh.sample_id{i}));
        if numel(j)~=1,passed=false;continue;end
        passed=passed&&strcmp(old.best_candidate(j),fresh.best_candidate{i})&& ...
            strcmp(old.state(j),fresh.state{i})&& ...
            strcmp(old.candidate_set(j),fresh.candidate_set{i})&& ...
            old.set_size(j)==fresh.set_size(i)&& ...
            abs(old.distance_1(j)-fresh.distance_1(i))<= ...
            1e-9+1e-10*abs(old.distance_1(j));
    end
end
function peak=process_peak_rss_kb()
    peak=NaN;if ~isunix,return;end
    data=fileread('/proc/self/status');
    token=regexp(data,'VmHWM:\s*(\d+)\s*kB','tokens','once');
    if ~isempty(token),peak=str2double(token{1});end
end
