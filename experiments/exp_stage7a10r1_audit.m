function out=exp_stage7a10r1_audit(root)
%EXP_STAGE7A10R1_AUDIT Read-only Stage 7A.10 confirm1 denominator/effect audit.
    if nargin<1||isempty(root),root=fileparts(fileparts(mfilename('fullpath')));end
    addpath(fullfile(root,'src'));
    source=fullfile(root,'results','data','stage7a_10','formal','confirm1','samples.csv');
    samples=readtable(source,'TextType','string');
    assert(height(samples)==12960,'stage7a10r1:ConfirmIdentity');
    outdir=fullfile(root,'results','data','stage7a_10_r1','audit');
    assert(exist(fullfile(outdir,'metadata.csv'),'file')~=2, ...
        'stage7a10r1:ExistingAudit');
    derived=stage7a10r1_derive_statistics(samples);
    d=samples(samples.method=="D_adaptive",:);
    n=height(d);
    condition=d.scenario;library=d.library;truth_id=d.truth_id;
    noise_seed=d.noise_seed;selected_view=d.selected_view;
    selected_terminal=ismember(selected_view,[3 7]);
    selected_node=ismember(selected_view,[12 14 16]);
    no_extra=selected_view==0;
    assert(all(selected_terminal|selected_node|no_extra), ...
        'stage7a10r1:UnknownView');
    node_bias=condition=="T_node_port_error" & ...
        abs(d.node_port_error_fraction)>0 & selected_node;
    termination_bias=condition=="T_termination_error" & ...
        abs(d.termination_error_fraction)>0 & selected_terminal;
    old_load_drift=condition=="T_load_drift" & ...
        abs(d.load_drift_fraction)>0 & selected_terminal;
    effective=node_bias|termination_bias|old_load_drift;
    applicability=table(condition,library,truth_id,noise_seed,selected_view, ...
        selected_terminal,selected_node,no_extra,node_bias,termination_bias, ...
        old_load_drift,effective);
    groups=unique(applicability(:,{'condition','library'}));
    summary=table('Size',[height(groups) 9], ...
        'VariableTypes',{'string','string','double','double','double', ...
        'double','double','double','double'}, ...
        'VariableNames',{'condition','library','n','selected_terminal_n', ...
        'selected_node_n','no_extra_n','node_bias_effective_n', ...
        'termination_bias_effective_n','old_load_drift_effective_n'});
    for k=1:height(groups)
        mask=condition==groups.condition(k)&library==groups.library(k);
        summary(k,:)={groups.condition(k),groups.library(k),nnz(mask), ...
            nnz(selected_terminal(mask)),nnz(selected_node(mask)), ...
            nnz(no_extra(mask)),nnz(node_bias(mask)), ...
            nnz(termination_bias(mask)),nnz(old_load_drift(mask))};
    end
    if exist(outdir,'dir')~=7,mkdir(outdir);end
    writetable(derived,fullfile(outdir,'confirm1_derived_statistics.csv'));
    writetable(applicability,fullfile(outdir,'confirm1_applicability.csv'));
    writetable(summary,fullfile(outdir,'confirm1_applicability_summary.csv'));
    metadata=table("Stage 7A.10-R.1","b76972dceb17e46710afcd8b10b8e3f19b9f0a31", ...
        string(stage4a7_2_r2_sha256_file(source)),height(samples),string(version), ...
        string(computer('arch')), ...
        'VariableNames',{'stage','source_commit','confirm1_samples_sha256', ...
        'source_rows','matlab_version','architecture'});
    writetable(metadata,fullfile(outdir,'metadata.csv'));
    fprintf('Stage 7A.10-R.1 read-only audit: %d source rows, %d derived rows, %d D rows.\n', ...
        height(samples),height(derived),n);
    out=struct('output_dir',outdir,'derived_rows',height(derived), ...
        'adaptive_rows',n);
end
