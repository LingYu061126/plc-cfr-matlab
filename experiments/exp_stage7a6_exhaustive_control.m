function out=exp_stage7a6_exhaustive_control(root)
%EXP_STAGE7A6_EXHAUSTIVE_CONTROL Small, post-protocol diagnostic only.
%   Compare budget-17 traversal with direct fitting of all 17 stored graphs
%   on the first held-out replicate of each new-A topology and each view.
%   No test truth or direct-fit result is used to change a threshold/search.
    if nargin<1||isempty(root),root=fileparts(fileparts(mfilename('fullpath')));end
    addpath(fullfile(root,'src'),fullfile(root,'config'));
    base=default_config(root);cfg=stage7a6_config(base,'formal',17);
    [pool,base_ix,~,catalog,groups]=stage7a6_candidate_space(base);
    bank=stage7a5_template_bank(pool,base,cfg);
    E=stage7a5_generate_split(catalog,groups.inlib,base,cfg, ...
        cfg.seed_E,cfg.n_E_per_class,'E',false);
    sigma=zeros(1,2);
    for k=1:numel(E)
        for v=1:2
            sigma(v)=sigma(v)+mean(abs(E(k).observed{v}-E(k).clean{v}).^2);
        end
    end
    sigma=sqrt(sigma/numel(E));
    samples=stage7a5_generate_split(catalog,groups.reachable,base,cfg, ...
        cfg.seed_T_reachable,1,'T_reachable',false);
    rows=repmat(struct('truth_id','','scheme','','sample_seed',0, ...
        'budget17_candidate_count',0,'budget17_best','','budget17_truth_rank',0, ...
        'direct17_best','','direct17_truth_rank',0,'best_changed',false, ...
        'truth_distance_budget17',NaN,'truth_distance_direct17',NaN, ...
        'direct17_best_distance',NaN),0,1);
    for v=1:numel(cfg.observation_views)
        views=cfg.observation_views{v};scheme=cfg.observation_schemes{v};
        for k=1:numel(samples)
            sample=samples(k);
            budget=stage7a6_score_observation(sample.observed,pool,bank, ...
                base,cfg,base_ix,views,sigma,17,[]);
            direct=stage7a5_profile(sample.observed,pool,bank,base,cfg, ...
                1:numel(pool),views,sigma,cfg.frequency_train_indices,true);
            [~,bix]=min(budget.distances);[~,dix]=min(direct.distances);
            bt=find(strcmp(budget.candidate_ids,sample.truth_id),1);
            dt=find(strcmp(direct.candidate_ids,sample.truth_id),1);
            [~,bord]=sort(budget.distances);[~,dord]=sort(direct.distances);
            row=rows_template();row.truth_id=sample.truth_id;row.scheme=scheme;
            row.sample_seed=sample.parameter_seed;
            row.budget17_candidate_count=numel(budget.candidate_ids);
            row.budget17_best=budget.candidate_ids{bix};
            row.direct17_best=direct.candidate_ids{dix};
            if ~isempty(bt)
                row.budget17_truth_rank=find(bord==bt,1);
                row.truth_distance_budget17=budget.distances(bt);
            end
            row.direct17_truth_rank=find(dord==dt,1);
            row.truth_distance_direct17=direct.distances(dt);
            row.direct17_best_distance=direct.distances(dix);
            row.best_changed=~strcmp(row.budget17_best,row.direct17_best);
            rows(end+1)=row; %#ok<AGROW>
        end
    end
    oldcfg=stage7a5_config(base,'formal');
    [oldpool]=stage7a5_candidate_pool(base);
    ids={oldpool.topology_id};g=find(strcmp(ids,'G003'),1);
    m=find(strcmp(ids,'MIRROR_M3'),1);
    mirror=repmat(struct('main_scale',0,'load_scale',0, ...
        'max_complex_h_difference',0,'relative_rms_h_difference',0, ...
        'max_complex_zin_difference',0,'relative_rms_zin_difference',0),0,1);
    pairs=[0.98 0.8;1 1;1.02 1.2];
    for k=1:size(pairs,1)
        theta=struct('main_length_scale',pairs(k,1), ...
            'branch_length_scale',1,'branch_load_scale',pairs(k,2), ...
            'first_segment_scale',1,'source_impedance_ohm',50, ...
            'receiver_impedance_ohm',50);
        z1=stage7a4_forward_state(oldpool(g).network,theta,base, ...
            oldcfg.frequency_hz,oldcfg.state_50);
        z2=stage7a4_forward_state(oldpool(m).network,theta,base, ...
            oldcfg.frequency_hz,oldcfg.state_50);
        mirror(end+1)=struct('main_scale',pairs(k,1), ...
            'load_scale',pairs(k,2), ...
            'max_complex_h_difference',max(abs(z1.H_endpoint-z2.H_endpoint)), ...
            'relative_rms_h_difference', ...
                sqrt(mean(abs(z1.H_endpoint-z2.H_endpoint).^2))/ ...
                sqrt(mean(abs(z1.H_endpoint).^2)), ...
            'max_complex_zin_difference',max(abs(z1.Zin-z2.Zin)), ...
            'relative_rms_zin_difference', ...
                sqrt(mean(abs(z1.Zin-z2.Zin).^2))/ ...
                sqrt(mean(abs(z1.Zin).^2))); %#ok<AGROW>
    end
    extra=repmat(mirror(1),0,1);
    ids={pool.topology_id};left=find(strcmp(ids,'EXT_021'),1);
    right=find(strcmp(ids,'EXT_120'),1);
    for k=1:size(pairs,1)
        theta=struct('main_length_scale',pairs(k,1), ...
            'branch_length_scale',1,'branch_load_scale',pairs(k,2), ...
            'first_segment_scale',1,'source_impedance_ohm',50, ...
            'receiver_impedance_ohm',50);
        z1=stage7a4_forward_state(pool(left).network,theta,base, ...
            cfg.frequency_hz,cfg.state_50);
        z2=stage7a4_forward_state(pool(right).network,theta,base, ...
            cfg.frequency_hz,cfg.state_50);
        extra(end+1)=struct('main_scale',pairs(k,1), ...
            'load_scale',pairs(k,2), ...
            'max_complex_h_difference',max(abs(z1.H_endpoint-z2.H_endpoint)), ...
            'relative_rms_h_difference', ...
                sqrt(mean(abs(z1.H_endpoint-z2.H_endpoint).^2))/ ...
                sqrt(mean(abs(z1.H_endpoint).^2)), ...
            'max_complex_zin_difference',max(abs(z1.Zin-z2.Zin)), ...
            'relative_rms_zin_difference', ...
                sqrt(mean(abs(z1.Zin-z2.Zin).^2))/ ...
                sqrt(mean(abs(z1.Zin).^2))); %#ok<AGROW>
    end
    dirout=fullfile(root,'results','data','stage7a_6','audit');
    if ~exist(dirout,'dir'),mkdir(dirout);end
    writetable(struct2table(rows),fullfile(dirout,'exhaustive17_control.csv'));
    writetable(struct2table(mirror),fullfile(dirout,'mirror_noiseless_control.csv'));
    writetable(struct2table(extra),fullfile(dirout,'extended_noiseless_control.csv'));
    fprintf('Stage 7A.6 direct-17 control: %d rows; no-noise pair checks %d + %d\n', ...
        numel(rows),numel(mirror),numel(extra));
    out=struct('direct17',rows,'mirror',mirror,'extended',extra);
end
function row=rows_template()
    row=struct('truth_id','','scheme','','sample_seed',0, ...
        'budget17_candidate_count',0,'budget17_best','','budget17_truth_rank',0, ...
        'direct17_best','','direct17_truth_rank',0,'best_changed',false, ...
        'truth_distance_budget17',NaN,'truth_distance_direct17',NaN, ...
        'direct17_best_distance',NaN);
end
