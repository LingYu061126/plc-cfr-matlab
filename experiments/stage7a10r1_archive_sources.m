function stage7a10r1_archive_sources(root)
%STAGE7A10R1_ARCHIVE_SOURCES Hash raw bytes of R.1 and frozen input artifacts.
%   Repository-relative paths; inventory files do not hash themselves.
    if nargin<1||isempty(root),root=fileparts(fileparts(mfilename('fullpath')));end
    addpath(fullfile(root,'src'));
    source={ ...
        'config/stage7a10r1_config.m', ...
        'docs/stage7a10_r1_protocol.md','docs/stage7a10_r1_report.md', ...
        'run_stage7a10r1_audit.m','run_stage7a10r1_study.m', ...
        'src/stage7a10r1_measure_views.m', ...
        'src/stage7a10r1_derive_statistics.m', ...
        'experiments/exp_stage7a10r1_audit.m', ...
        'experiments/exp_stage7a10r1_study.m', ...
        'experiments/exp_stage7a10r1_postprocess.m', ...
        'experiments/stage7a10r1_archive_sources.m', ...
        'tests/test_stage7a10r1_statistics.m', ...
        'tests/test_stage7a10r1_integrity.m'};
    artifact={ ...
        'results/data/stage7a_10/formal/confirm1/samples.csv', ...
        'results/data/stage7a_10/formal/confirm1/config_snapshot.mat', ...
        'results/data/stage7a_10_r1/audit/confirm1_derived_statistics.csv', ...
        'results/data/stage7a_10_r1/audit/confirm1_applicability.csv', ...
        'results/data/stage7a_10_r1/audit/confirm1_applicability_summary.csv', ...
        'results/data/stage7a_10_r1/audit/confirm1_view_counts.csv', ...
        'results/data/stage7a_10_r1/audit/metadata.csv', ...
        'results/data/stage7a_10_r1/smoke/smoke1/samples.csv', ...
        'results/data/stage7a_10_r1/smoke/smoke1/derived_statistics.csv', ...
        'results/data/stage7a_10_r1/smoke/smoke1/paired_changes.csv', ...
        'results/data/stage7a_10_r1/smoke/smoke1/metadata.csv', ...
        'results/data/stage7a_10_r1/smoke/smoke1/config_snapshot.mat', ...
        'results/data/stage7a_10_r1/formal/formal1/samples.csv', ...
        'results/data/stage7a_10_r1/formal/formal1/derived_statistics.csv', ...
        'results/data/stage7a_10_r1/formal/formal1/paired_changes.csv', ...
        'results/data/stage7a_10_r1/formal/formal1/paired_score_changes.csv', ...
        'results/data/stage7a_10_r1/formal/formal1/measurement_cost.csv', ...
        'results/data/stage7a_10_r1/formal/formal1/metadata.csv', ...
        'results/data/stage7a_10_r1/formal/formal1/config_snapshot.mat', ...
        'results/logs/stage7a_10_r1/confirm1_readonly_audit.log', ...
        'results/logs/stage7a_10_r1/smoke_smoke1.log', ...
        'results/logs/stage7a_10_r1/formal_formal1.log'};
    folder=fullfile(root,'results','data','stage7a_10_r1','archive');
    if exist(folder,'dir')~=7,mkdir(folder);end
    writetable(struct2table(rows(root,source,'source')), ...
        fullfile(folder,'source_inventory.csv'));
    writetable(struct2table(rows(root,artifact,'artifact')), ...
        fullfile(folder,'artifact_manifest.csv'));
    fprintf('Stage 7A.10-R.1 inventory: %d sources, %d artifacts.\n', ...
        numel(source),numel(artifact));
end
function out=rows(root,paths,category)
    out=repmat(struct('relative_path',"",'sha256',"",'size_bytes',0, ...
        'category',"",'audit_baseline_commit',""),numel(paths),1);
    for k=1:numel(paths)
        p=fullfile(root,strrep(paths{k},'/',filesep));
        assert(exist(p,'file')==2,'stage7a10r1:MissingArtifact', ...
            'Missing file %s',paths{k});
        info=dir(p);
        out(k)=struct('relative_path',string(paths{k}), ...
            'sha256',string(stage4a7_2_r2_sha256_file(p)), ...
            'size_bytes',info.bytes,'category',string(category), ...
            'audit_baseline_commit',"b76972dceb17e46710afcd8b10b8e3f19b9f0a31");
    end
end
