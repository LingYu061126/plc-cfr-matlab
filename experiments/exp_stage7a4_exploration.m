function result=exp_stage7a4_exploration(root,mode)
%EXP_STAGE7A4_EXPLORATION Calibrate error units and select B/C before T.
    if nargin<1||isempty(root),root=fileparts(fileparts(mfilename('fullpath')));end
    if nargin<2||isempty(mode),mode='formal';end
    addpath(fullfile(root,'src'),fullfile(root,'config'));
    base=default_config(root);cfg=stage7a4_mirror_observation_config(base,mode);
    if exist(cfg.output_dir,'dir')~=7,mkdir(cfg.output_dir);end
    t=tic;[all4,pair,original]=stage7a4_fixed_topologies(base);
    bank=stage7a4_template_bank(all4,base,cfg);
    [e,e_time]=stage7a4_generate_split(all4,1:4,base,cfg,cfg.seed_E, ...
        cfg.n_E_per_topology,cfg.cfr_snr_db,'standard');
    sigma=stage7a4_calibrate_view_scales(e,cfg);
    rows=repmat(info_row(),0,1);h_only=zeros(1,numel(cfg.termination_ohm));
    joint=zeros(1,numel(cfg.termination_ohm));
    for k=1:numel(cfg.termination_ohm)
        ix=2*k-1;
        kinds={{ix,'CFR'},{ix+1,'Zin'},{[ix ix+1],'CFR_plus_Zin'}};
        for j=1:3
            view_indices=kinds{j}{1};label=kinds{j}{2};
            info=stage7a4_information_distance(bank,pair,view_indices,sigma);
            rows(end+1)=make_row(info,sprintf('A1_%g_%s',cfg.termination_ohm(k),label), ...
                'A1',cfg.termination_ohm(k),0,view_indices); %#ok<AGROW>
            if j==1,h_only(k)=info.min_joint_distance;end
            if j==3,joint(k)=info.min_joint_distance;end
        end
    end
    c_joint=zeros(1,numel(cfg.node_indices));
    for k=1:numel(cfg.node_indices)
        ix=2*numel(cfg.termination_ohm)+2*k-1;
        kinds={{ix,'endpoint_loaded'},{ix+1,'node_CFR'},{[ix ix+1],'joint_CFR'}};
        for j=1:3
            view_indices=kinds{j}{1};label=kinds{j}{2};
            info=stage7a4_information_distance(bank,pair,view_indices,sigma);
            rows(end+1)=make_row(info,sprintf('C_M%d_%s',cfg.node_indices(k)-1,label), ...
                'C',50,cfg.node_indices(k),view_indices); %#ok<AGROW>
            if j==3,c_joint(k)=info.min_joint_distance;end
        end
    end
    b_candidates=setdiff(1:numel(cfg.termination_ohm),3);
    passing=b_candidates(h_only(b_candidates)>=cfg.separation_threshold);
    if ~isempty(passing)
        cost=abs(log(cfg.termination_ohm(passing)/50));
        passing_term=cfg.termination_ohm(passing);
        [~,ord]=sortrows([cost(:),passing_term(:)]);
        b=passing(ord(1));b_rule='first_H_only_separation_at_minimum_log_termination_change';
    else
        candidate_term=cfg.termination_ohm(b_candidates);
        candidate_h=h_only(b_candidates);
        [~,ord]=sortrows([-candidate_h(:), ...
            abs(log(candidate_term(:)/50)),candidate_term(:)]);
        b=b_candidates(ord(1));b_rule='maximum_H_only_separation_if_none_pass';
    end
    [~,c]=max(c_joint);c_rule='maximum_joint_node_separation_tie_first_M1';
    crossings=find((joint(1:end-1)-cfg.separation_threshold).* ...
        (joint(2:end)-cfg.separation_threshold)<0);
    fine_ohm=NaN;fine_interval='none';
    if ~isempty(crossings)
        cost=abs(log(sqrt(cfg.termination_ohm(crossings).* ...
            cfg.termination_ohm(crossings+1))/50));
        [~,j]=min(cost);k=crossings(j);
        fine_ohm=sqrt(cfg.termination_ohm(k)*cfg.termination_ohm(k+1));
        fine_interval=sprintf('%g_to_%g',cfg.termination_ohm(k),cfg.termination_ohm(k+1));
    end
    scale_rows=repmat(struct('view_name','','view_index',0,'error_rms',0,'unit',''), ...
        numel(sigma),1);
    for v=1:numel(sigma)
        unit='normalized_complex_CFR';if startsWith(cfg.view_names{v},'Zin'),unit='ohm';end
        scale_rows(v)=struct('view_name',cfg.view_names{v},'view_index',v, ...
            'error_rms',sigma(v),'unit',unit);
    end
    topo_rows=repmat(struct('candidate_id','','signature','','in_original_library',false, ...
        'in_diagnostic_pair',false,'branch_main_node',0,'main_lengths_m','', ...
        'branch_length_m',NaN,'branch_load_ohm',NaN),4,1);
    for k=1:4
        branches=all4(k).network.branches;bn=0;bl=NaN;bz=NaN;
        if ~isempty(branches),bn=branches(1).node;bl=branches(1).length;bz=branches(1).load;end
        topo_rows(k)=struct('candidate_id',all4(k).topology_id, ...
            'signature',stage6b_network_signature(all4(k).network), ...
            'in_original_library',ismember(k,original), ...
            'in_diagnostic_pair',ismember(k,pair),'branch_main_node',bn, ...
            'main_lengths_m',mat2str(all4(k).network.main_lengths), ...
            'branch_length_m',bl,'branch_load_ohm',bz);
    end
    selection=struct('selected_B_termination_ohm',cfg.termination_ohm(b), ...
        'selected_B_state_index',b,'B_selection_rule',b_rule, ...
        'selected_C_node_index',cfg.node_indices(c), ...
        'selected_C_main_label',sprintf('M%d',cfg.node_indices(c)-1), ...
        'C_selection_rule',c_rule,'A1_fine_termination_ohm',fine_ohm, ...
        'A1_fine_interval',fine_interval,'pair_ids',strjoin(bank.candidate_ids(pair),','), ...
        'original_library_ids',strjoin(bank.candidate_ids(original),','), ...
        'bank_identity',bank.identity,'E_seed_base',cfg.seed_E, ...
        'E_samples_per_topology',cfg.n_E_per_topology, ...
        'cache_bytes',bank.logical_cache_bytes,'cache_build_time_s',bank.build_time_s, ...
        'E_generation_time_s',e_time,'exploration_wall_s',toc(t));
    writetable(struct2table(rows),fullfile(cfg.output_dir,'stage7a4_exploration.csv'));
    writetable(struct2table(scale_rows),fullfile(cfg.output_dir,'stage7a4_error_scales.csv'));
    writetable(struct2table(topo_rows),fullfile(cfg.output_dir,'stage7a4_topologies.csv'));
    port_rows=repmat(struct('state_index',0,'state_name','','source_node','M0_TX', ...
        'source_ohm',50,'endpoint_receiver_node','M4_RX', ...
        'endpoint_termination_ohm',50,'internal_node','none', ...
        'internal_receiver_input_ohm',NaN,'port_reference_ohm',50, ...
        'normalization','H_port=2*Vreceiver/Vsource_at_Zs50'),numel(cfg.states),1);
    for k=1:numel(cfg.states)
        s=cfg.states(k);label='none';zin=NaN;
        if s.node_index>0,label=sprintf('M%d',s.node_index-1);zin=s.node_load_ohm;end
        port_rows(k)=struct('state_index',k,'state_name',s.name, ...
            'source_node','M0_TX','source_ohm',50, ...
            'endpoint_receiver_node','M4_RX', ...
            'endpoint_termination_ohm',s.receiver_ohm, ...
            'internal_node',label,'internal_receiver_input_ohm',zin, ...
            'port_reference_ohm',50, ...
            'normalization','H_port=2*Vreceiver/Vsource_at_Zs50');
    end
    writetable(struct2table(port_rows),fullfile(cfg.output_dir,'stage7a4_port_catalog.csv'));
    writetable(struct2table(selection),fullfile(cfg.output_dir,'stage7a4_selection.csv'));
    save(fullfile(cfg.output_dir,'stage7a4_exploration_snapshot.mat'), ...
        'cfg','selection','sigma','pair','original');
    fprintf('Stage 7A.4 exploration %s: B=%g ohm, C=M%d, fine=%g ohm, cache=%d bytes, %.3f s.\n', ...
        mode,cfg.termination_ohm(b),cfg.node_indices(c)-1,fine_ohm, ...
        bank.logical_cache_bytes,selection.exploration_wall_s);
    result=struct('cfg',cfg,'base',base,'all4',all4,'pair_indices',pair, ...
        'original_indices',original,'bank',bank,'sigma',sigma, ...
        'selected_B_index',b,'selected_C_index',c,'selection',selection, ...
        'information_rows',rows);
end
function out=info_row()
    out=struct('scheme','','stage','','receiver_ohm',NaN,'node_index',0, ...
        'view_indices','','view_count',0,'fixed_joint_distance',NaN, ...
        'min_profile_joint_distance',NaN,'fixed_abs_rms_per_view','', ...
        'fixed_relative_rms_per_view','','profiled_abs_rms_per_view','', ...
        'best_params_G003','','best_params_mirror','', ...
        'numerically_identical_at_nominal',false);
end
function out=make_row(info,name,stage,zr,node,views)
    out=info_row();out.scheme=name;out.stage=stage;out.receiver_ohm=zr;
    out.node_index=node;out.view_indices=mat2str(views);out.view_count=numel(views);
    out.fixed_joint_distance=info.fixed_joint_distance;
    out.min_profile_joint_distance=info.min_joint_distance;
    out.fixed_abs_rms_per_view=mat2str(info.fixed_abs_rms_per_view,16);
    out.fixed_relative_rms_per_view=mat2str(info.fixed_relative_rms_per_view,16);
    out.profiled_abs_rms_per_view=mat2str(info.profiled_abs_rms_per_view,16);
    out.best_params_G003=mat2str(info.best_params_a,16);
    out.best_params_mirror=mat2str(info.best_params_b,16);
    out.numerically_identical_at_nominal=info.numerically_identical_at_nominal;
end
