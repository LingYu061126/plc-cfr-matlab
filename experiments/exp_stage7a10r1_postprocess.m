function out=exp_stage7a10r1_postprocess(root,run_id)
%EXP_STAGE7A10R1_POSTPROCESS Read-only score-delta and state-cost audit.
%   Uses R.1 raw samples; never updates calibration or scientific results.
    if nargin<1||isempty(root),root=fileparts(fileparts(mfilename('fullpath')));end
    if nargin<2||isempty(run_id),run_id='formal1';end
    folder=fullfile(root,'results','data','stage7a_10_r1','formal',run_id);
    s=readtable(fullfile(folder,'samples.csv'),'TextType','string');
    assert(height(s)==12960,'stage7a10r1:SampleIdentity');
    base=s(s.scenario=="baseline",:);
    variant=s(s.scenario~="baseline",:);
    keys=string(base.method)+"/"+string(base.library)+"/"+string(base.noise_seed);
    assert(numel(unique(keys))==height(base),'stage7a10r1:BaseKeys');
    lookup=containers.Map(cellstr(keys),num2cell(1:height(base)));
    proto=struct('scenario',"",'method',"",'library',"",'truth_id',"", ...
        'noise_seed',0,'effective',false,'used_clean_rms_delta',0, ...
        'baseline_distance',NaN,'perturbed_distance',NaN, ...
        'absolute_distance_change',NaN,'baseline_margin',NaN, ...
        'perturbed_margin',NaN,'absolute_margin_change',NaN, ...
        'candidate_set_changed',false,'state_changed',false);
    delta=repmat(proto,height(variant),1);
    for i=1:height(variant)
        v=variant(i,:);
        key=char(v.method+"/"+v.library+"/"+string(v.noise_seed));
        assert(isKey(lookup,key),'stage7a10r1:PairMissing');
        b=base(lookup(key),:);
        assert(b.truth_id==v.truth_id&&b.selected_view==v.selected_view, ...
            'stage7a10r1:PairChanged');
        delta(i)=struct('scenario',v.scenario,'method',v.method, ...
            'library',v.library,'truth_id',v.truth_id,'noise_seed',v.noise_seed, ...
            'effective',v.effective_on_used_observation, ...
            'used_clean_rms_delta',v.used_clean_rms_delta, ...
            'baseline_distance',b.distance,'perturbed_distance',v.distance, ...
            'absolute_distance_change',abs(v.distance-b.distance), ...
            'baseline_margin',b.margin,'perturbed_margin',v.margin, ...
            'absolute_margin_change',abs(v.margin-b.margin), ...
            'candidate_set_changed',b.candidate_set~=v.candidate_set, ...
            'state_changed',b.decision_state~=v.decision_state);
    end
    paired_scores=struct2table(delta);
    scenarios=unique(s.scenario);methods=unique(s.method);libraries=unique(s.library);
    cost=table('Size',[numel(scenarios)*numel(methods)*numel(libraries) 15], ...
        'VariableTypes',{'string','string','string','double','double','double', ...
        'double','double','double','double','double','double','double', ...
        'double','double'}, ...
        'VariableNames',{'scenario','method','library','scored_rows', ...
        'selected_node_n','selected_terminal_n','no_extra_n','effective_n', ...
        'source_excitations_sum','source_excitations_mean', ...
        'node_switches_sum','termination_switches_sum', ...
        'internal_receiver_nodes_mean','scoring_wall_s_sum', ...
        'scoring_wall_s_mean'});
    k=0;
    for a=1:numel(scenarios)
        for m=1:numel(methods)
            for q=1:numel(libraries)
                z=s(s.scenario==scenarios(a)&s.method==methods(m)& ...
                    s.library==libraries(q),:);
                k=k+1;
                cost(k,:)={scenarios(a),methods(m),libraries(q),height(z), ...
                    nnz(ismember(z.selected_view,[12 14 16])), ...
                    nnz(ismember(z.selected_view,[3 7])),nnz(z.method=="D_adaptive" & ...
                    z.selected_view==0),nnz(z.effective_on_used_observation), ...
                    sum(z.source_excitations),mean(z.source_excitations), ...
                    sum(z.node_port_switches),sum(z.termination_switches), ...
                    mean(z.internal_receiver_nodes),sum(z.wall_s),mean(z.wall_s)};
            end
        end
    end
    writetable(paired_scores,fullfile(folder,'paired_score_changes.csv'));
    writetable(cost,fullfile(folder,'measurement_cost.csv'));
    audit_folder=fullfile(root,'results','data','stage7a_10_r1','audit');
    old=readtable(fullfile(audit_folder,'confirm1_applicability.csv'), ...
        'TextType','string');
    old_groups=unique(old(:,{'condition','library'}));
    view_rows=table('Size',[height(old_groups)*6 5], ...
        'VariableTypes',{'string','string','double','string','double'}, ...
        'VariableNames',{'condition','library','view_index','view_name','n'});
    view_ids=[0 3 7 12 14 16];
    view_names=["no_extra","H25","H100","M1","M2","M3"];
    cursor=0;
    for i=1:height(old_groups)
        for j=1:numel(view_ids)
            cursor=cursor+1;
            view_rows(cursor,:)={old_groups.condition(i),old_groups.library(i), ...
                view_ids(j),view_names(j), ...
                nnz(old.condition==old_groups.condition(i)& ...
                    old.library==old_groups.library(i)& ...
                    old.selected_view==view_ids(j))};
        end
    end
    writetable(view_rows,fullfile(audit_folder,'confirm1_view_counts.csv'));
    fprintf('PASS R.1 postprocess: %d paired score rows, %d cost rows.\n', ...
        height(paired_scores),height(cost));
    out=struct('paired_rows',height(paired_scores),'cost_rows',height(cost));
end
