function stage7a10_archive_sources(root)
%STAGE7A10_ARCHIVE_SOURCES Hash Stage 7A.10 source and final artifacts.
%   Inventories use repository-relative paths and raw-byte SHA-256. They do
%   not hash themselves, so no recursive manifest dependency exists.
    if nargin<1||isempty(root),root=fileparts(fileparts(mfilename('fullpath')));end
    addpath(fullfile(root,'src'));
    source={ ...
        'config/stage7a10_config.m', ...
        'docs/stage7a10_protocol.md','docs/stage7a10_report.md', ...
        'run_stage7a10_study.m', ...
        'src/stage7a10_view_selection.m', ...
        'src/stage7a10_adaptive_profile.m', ...
        'src/stage7a10_calibrate.m','src/stage7a10_decide.m', ...
        'experiments/exp_stage7a10_study.m', ...
        'experiments/exp_stage7a10_controls.m', ...
        'experiments/exp_stage7a10_ports_off.m', ...
        'experiments/stage7a10_archive_sources.m', ...
        'tests/test_stage7a10_adaptive.m', ...
        'tests/test_stage7a10_result_integrity.m'};
    sources=rows(root,source,'source');
    artifact={ ...
        'results/data/stage7a_10/formal/confirm1/samples.csv', ...
        'results/data/stage7a_10/formal/confirm1/summary.csv', ...
        'results/data/stage7a_10/formal/confirm1/topologies.csv', ...
        'results/data/stage7a_10/formal/confirm1/calibration.csv', ...
        'results/data/stage7a_10/formal/confirm1/view_selection.csv', ...
        'results/data/stage7a_10/formal/confirm1/metadata.csv', ...
        'results/data/stage7a_10/formal/confirm1/config_snapshot.mat', ...
        'results/data/stage7a_10/formal/controls/confirm1/samples.csv', ...
        'results/data/stage7a_10/formal/controls/confirm1/separation.csv', ...
        'results/data/stage7a_10/formal/controls/confirm1/metadata.csv', ...
        'results/data/stage7a_10/formal/ports_off/confirm1/samples.csv', ...
        'results/data/stage7a_10/formal/ports_off/confirm1/metadata.csv', ...
        'results/logs/stage7a_10/formal_confirm1.log', ...
        'results/logs/stage7a_10/auxiliary_confirm1.log'};
    artifacts=rows(root,artifact,'artifact');
    folder=fullfile(root,'results','data','stage7a_10','archive');
    if exist(folder,'dir')~=7,mkdir(folder);end
    writetable(struct2table(sources),fullfile(folder,'source_inventory.csv'));
    writetable(struct2table(artifacts),fullfile(folder,'artifact_manifest.csv'));
    fprintf('Stage 7A.10 inventory: %d sources, %d artifacts.\n', ...
        numel(sources),numel(artifacts));
end
function out=rows(root,paths,kind)
    out=repmat(struct('relative_path','','sha256','','size_bytes',0, ...
        'category','','baseline_commit',''),numel(paths),1);
    for k=1:numel(paths)
        path=fullfile(root,strrep(paths{k},'/',filesep));
        assert(exist(path,'file')==2,'stage7a10:MissingArtifact', ...
            'Missing file %s',paths{k});
        info=dir(path);
        out(k)=struct('relative_path',paths{k}, ...
            'sha256',stage4a7_2_r2_sha256_file(path), ...
            'size_bytes',info.bytes,'category',kind, ...
            'baseline_commit','1c7ae4a40f641d37c44a35b3d64278af19fcc98f');
    end
end
