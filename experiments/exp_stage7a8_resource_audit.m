function out=exp_stage7a8_resource_audit(root,mode)
%EXP_STAGE7A8_RESOURCE_AUDIT Independent per-sample resource replay.
%   Uses the frozen Stage 7A.8 formal model and T seeds. The two observed
%   views are complex 1-by-F vectors; distance/statistic units are normalized.
    base=default_config(root);cfg=stage7a8_config(base,mode);
    output_dir=fullfile(root,'results','data','stage7a_8', ...
        'resource_audit',mode);
    if ~exist(output_dir,'dir'),mkdir(output_dir);end
    formal_dir=fullfile(root,'results','data','stage7a_8',mode);
    frozen=load(fullfile(formal_dir,'config_snapshot.mat'),'model','sigma','cfg');
    assert(isequal(cfg.frequency_hz,frozen.cfg.frequency_hz)&& ...
        isequal(cfg.frequency_train_indices, ...
            frozen.cfg.frequency_train_indices)&& ...
        isequal(cfg.frequency_holdout_indices, ...
            frozen.cfg.frequency_holdout_indices)&& ...
        isequal(cfg.main_scale_grid,frozen.cfg.main_scale_grid)&& ...
        isequal(cfg.load_scale_grid,frozen.cfg.load_scale_grid), ...
        'stage7a8:ResourceProtocolMismatch');
    % The first smoke snapshot predates the condition-identity label fix.
    % Replay its recorded label, without changing any scientific setting.
    cfg.version=frozen.cfg.version;
    [pool,base_ix,~,catalog,groups]=stage7a7_candidate_space(base,cfg);
    bank=stage7a5_template_bank(pool,base,cfg);
    assert(strcmp(bank.identity,frozen.model.bank_identity)&& ...
        strcmp(bank.search_identity,frozen.model.search_identity)&& ...
        isequal(frozen.sigma,frozen.model.sigma), ...
        'stage7a8:ResourceIdentityMismatch');
    testcfg=cfg;testcfg.true_main_bounds=cfg.test_main_bounds;
    T=[stage7a5_generate_split(catalog,groups.inlib,base,testcfg, ...
        cfg.seed_T_inlib,cfg.n_T_inlib_per_topology,'T_inlib',false); ...
       stage7a5_generate_split(catalog,groups.old_out,base,testcfg, ...
        cfg.seed_T_old_out,cfg.n_T_old_out_per_topology,'T_old_out',false); ...
       stage7a5_generate_split(catalog,groups.reachable,base,testcfg, ...
        cfg.seed_T_reachable,cfg.n_T_reachable_per_topology,'T_reachable',false); ...
       stage7a5_generate_split(catalog,groups.grammar_out,base,testcfg, ...
        cfg.seed_T_grammar_out,cfg.n_T_grammar_out_per_topology, ...
        'T_grammar_out',false); ...
       stage7a5_generate_split(catalog,groups.domain,base,testcfg, ...
        cfg.seed_T_domain,cfg.n_T_domain_per_topology,'T_domain',true)];
    previous=readtable(fullfile(formal_dir,'samples.csv'), ...
        'TextType','string','Delimiter',',');
    prior_candidates=readtable(fullfile(formal_dir,'candidate_audit.csv'), ...
        'TextType','string','Delimiter',',');
    n=numel(T);assert(height(previous)==2*n&& ...
        height(prior_candidates)==2*n*37);
    rows=repmat(row_template(),2*n,1);t0=tic;
    for i=1:numel(T)
        s=T(i);sample_id=sprintf('%s_%s_%03d',s.split,s.truth_id,s.replicate);
        if mod(i,2)==1,order={'A','B'};else,order={'B','A'};end
        for j=1:2
            method=order{j};before=process_memory_kb();
            if strcmp(method,'A')
                score=stage7a7_score_observation(s.observed,pool,bank, ...
                    base,cfg,base_ix,[1 2],frozen.sigma,37,frozen.model);
            else
                score=stage7a8_score_observation(s.observed,pool,bank, ...
                    base,cfg,base_ix,[1 2],frozen.sigma,frozen.model);
            end
            decision=stage7a5_decide(score,frozen.model,bank);
            after=process_memory_kb();info=whos('score');
            mask=previous.sample_id==string(sample_id)& ...
                previous.method==string(method);
            assert(sum(mask)==1,'stage7a8:ResourceSampleIdentity');
            old=previous(mask,:);
            assert(old.parameter_seed==s.parameter_seed&& ...
                old.noise_seed==s.noise_seed&& ...
                old.optimizer_evaluations==score.optimizer_evaluations&& ...
                old.state==string(decision.decision_state)&& ...
                old.best_candidate==string(decision.best_candidate)&& ...
                old.candidate_set==string(strjoin(decision.candidate_set,';')));
            candidate_mask=prior_candidates.sample_id==string(sample_id)& ...
                prior_candidates.method==string(method);
            prior=prior_candidates(candidate_mask,:);
            assert(height(prior)==37&& ...
                isequal(cellstr(prior.candidate_id),score.candidate_ids(:))&& ...
                all(abs(prior.distance(:)-score.distances(:))<= ...
                    1e-9+1e-10*abs(score.distances(:)))&& ...
                all(abs(prior.fit_main_scale(:)-score.params(:,1))<=1e-6)&& ...
                all(abs(prior.fit_load_scale(:)-score.params(:,2))<=1e-6), ...
                'stage7a8:ResourceCandidateMismatch');
            r=row_template();r.sample_id=sample_id;r.method=method;
            r.split=s.split;r.scenario=s.scenario;
            r.parameter_seed=s.parameter_seed;r.noise_seed=s.noise_seed;
            r.candidate_count=numel(score.candidate_ids);
            r.optimizer_evaluations=score.optimizer_evaluations;
            r.forward_calls_search=score.optimizer_evaluations;
            r.forward_calls_holdout=1;
            r.forward_calls_total=score.optimizer_evaluations+1;
            r.scored_struct_bytes=info.bytes;
            r.rss_before_kb=before.rss;r.rss_after_kb=after.rss;
            r.process_hwm_before_kb=before.hwm;
            r.process_hwm_after_kb=after.hwm;
            r.shared_template_cache_bytes=bank.logical_cache_bytes;
            r.archived_scientific_match=true;
            rows(2*i-2+find(strcmp({'A','B'},method),1))=r;
        end
        if mod(i,10)==0||i==numel(T)
            fprintf('Stage 7A.8 resource replay %d/%d in %.3f s\n', ...
                i,numel(T),toc(t0));
        end
    end
    data=struct2table(rows);
    writetable(data,fullfile(output_dir,'per_sample_resources.csv'));
    [status,head]=system('git rev-parse HEAD');
    assert(status==0,'stage7a8:GitIdentity');head=strtrim(head);
    meta=table(string(head),string(version),string(computer('arch')), ...
        string(bank.identity),string(frozen.model.calibration_identity), ...
        bank.forward_calls,bank.logical_cache_bytes, ...
        max(data.process_hwm_after_kb),toc(t0),false,0, ...
        string('RSS before/after are snapshots; VmHWM is cumulative; no isolated per-sample peak'), ...
        'VariableNames',{'source_head','matlab_version','computer_arch', ...
        'bank_identity','calibration_identity','template_forward_calls', ...
        'template_cache_bytes','process_peak_rss_kb','runtime_s', ...
        'use_parallel','worker_count','memory_semantics'});
    writetable(meta,fullfile(output_dir,'metadata.csv'));
    assert(all(data.archived_scientific_match)&& ...
        all(data.forward_calls_total==data.optimizer_evaluations+1));
    fprintf('PASS Stage 7A.8 resource replay: %d scoring calls, %.3f s\n', ...
        height(data),meta.runtime_s);
    out=struct('output_dir',output_dir,'runtime_s',meta.runtime_s, ...
        'scoring_calls',height(data),'all_match',true);
end

function r=row_template()
    r=struct('sample_id','','method','','split','','scenario','', ...
        'parameter_seed',0,'noise_seed',0,'candidate_count',0, ...
        'optimizer_evaluations',0,'forward_calls_search',0, ...
        'forward_calls_holdout',0,'forward_calls_total',0, ...
        'scored_struct_bytes',0,'rss_before_kb',NaN,'rss_after_kb',NaN, ...
        'process_hwm_before_kb',NaN,'process_hwm_after_kb',NaN, ...
        'shared_template_cache_bytes',0,'archived_scientific_match',false);
end
function out=process_memory_kb()
    assert(isunix,'stage7a8:LinuxMemoryAudit');
    data=fileread('/proc/self/status');
    rss=regexp(data,'VmRSS:\s*(\d+)\s*kB','tokens','once');
    hwm=regexp(data,'VmHWM:\s*(\d+)\s*kB','tokens','once');
    assert(~isempty(rss)&&~isempty(hwm),'stage7a8:MemoryStatus');
    out=struct('rss',str2double(rss{1}),'hwm',str2double(hwm{1}));
end
