function out=exp_stage7a7_cost_profile(root)
%EXP_STAGE7A7_COST_PROFILE Post-formal, non-decision MATLAB profiler audit.
%   Reports per-call wall time and profiler function attributions for three
%   fixed synthetic scenes. These instrumented times are not formal runtimes.
    if nargin<1||isempty(root),root=fileparts(fileparts(mfilename('fullpath')));end
    addpath(fullfile(root,'src'),fullfile(root,'config'));
    base=default_config(root);cfg=stage7a7_config(base,'formal','nominal');
    [pool,base_ix,~,catalog,groups]=stage7a7_candidate_space(base,cfg);
    bank=stage7a5_template_bank(pool,base,cfg);
    E=stage7a5_generate_split(catalog,groups.inlib,base,cfg, ...
        cfg.seed_E,cfg.n_E_per_class,'E',false);
    sigma=zeros(1,2);
    for v=1:2
        squared=0;
        for k=1:numel(E)
            squared=squared+mean(abs(E(k).observed{v}-E(k).clean{v}).^2);
        end
        sigma(v)=sqrt(squared/numel(E));
    end
    cases=struct('name',{'G002','MID30','OUT10'}, ...
        'index',{groups.inlib(2),groups.reachable(1),groups.grammar_out(1)}, ...
        'seed',{cfg.seed_T_inlib,cfg.seed_T_reachable, ...
        cfg.seed_T_grammar_out});
    rows=repmat(struct('scenario','','budget',0,'candidate_count',0, ...
        'generated_by_edit_count',0,'completion_count',0, ...
        'optimizer_evaluations',0,'profile_evaluations',0, ...
        'score_wall_clock_s',NaN,'profile_s',NaN, ...
        'graph_edit_neighbors_s',NaN,'forward_state_s',NaN, ...
        'holdout_stat_s',NaN,'profiled_function_count',0),0,1);
    for c=1:numel(cases)
        sample=stage7a5_generate_split(catalog,cases(c).index,base,cfg, ...
            cases(c).seed,1,'T_cost',false);
        for budget=cfg.candidate_budgets
            profile('clear');profile('on');timer=tic;
            scored=stage7a7_score_observation(sample.observed,pool,bank, ...
                base,cfg,base_ix,[1 2],sigma,budget,[]);
            elapsed=toc(timer);profile('off');info=profile('info');
            rows(end+1)=struct('scenario',cases(c).name, ...
                'budget',budget,'candidate_count',numel(scored.candidate_ids), ...
                'generated_by_edit_count',numel(scored.generated_ids), ...
                'completion_count',numel(scored.completion_ids), ...
                'optimizer_evaluations',scored.optimizer_evaluations, ...
                'profile_evaluations',scored.profile_evaluations, ...
                'score_wall_clock_s',elapsed, ...
                'profile_s',function_time(info,'stage7a5_profile'), ...
                'graph_edit_neighbors_s', ...
                    function_time(info,'stage7a7_graph_edit_neighbors'), ...
                'forward_state_s',function_time(info,'stage7a4_forward_state'), ...
                'holdout_stat_s',function_time(info,'stage7a5_holdout_stat'), ...
                'profiled_function_count',numel(info.FunctionTable)); %#ok<AGROW>
        end
    end
    dirout=fullfile(root,'results','data','stage7a_7','audit');
    if ~exist(dirout,'dir'),mkdir(dirout);end
    writetable(struct2table(rows),fullfile(dirout,'posthoc_cost_profile.csv'));
    fprintf('PASS Stage 7A.7 posthoc cost profile: %d scored cases, %d templates in %.3f s\n', ...
        numel(rows),bank.forward_calls,bank.build_time_s);
    out=rows;
end
function elapsed=function_time(info,target)
    elapsed=0;
    for j=1:numel(info.FunctionTable)
        if strcmp(info.FunctionTable(j).FunctionName,target)
            elapsed=elapsed+info.FunctionTable(j).TotalTime;
        end
    end
end
