function out=exp_stage7a7_study(root,mode,condition)
%EXP_STAGE7A7_STUDY Paired serial CFR/Zin, junction and budget audit.
%   Truth and nuisance are confined to simulation and post-decision rows.
    if nargin<1||isempty(root),root=fileparts(fileparts(mfilename('fullpath')));end
    if nargin<2||isempty(mode),mode='formal';end
    if nargin<3||isempty(condition),condition='nominal';end
    addpath(fullfile(root,'src'),fullfile(root,'config'));
    base=default_config(root);cfg=stage7a7_config(base,mode,condition);
    if ~exist(cfg.output_dir,'dir'),mkdir(cfg.output_dir);end
    if ~exist(cfg.log_dir,'dir'),mkdir(cfg.log_dir);end
    started=tic;
    [pool,base_ix,grammar,catalog,groups,steps]= ...
        stage7a7_candidate_space(base,cfg);
    newbank=stage7a5_template_bank(pool,base,cfg);
    oldpool=pool(1:17);oldbank=[];
    if strcmp(condition,'nominal')
        oldcfg=cfg;oldcfg.candidate_budgets=[3 5 7 10 17];
        oldcfg.max_forward_template_evaluations=17* ...
            numel(cfg.main_scale_grid)*numel(cfg.load_scale_grid);
        oldbank=stage7a5_template_bank(oldpool,base,oldcfg);
        flows={'B','C17','C5','C12','C37'};
    else
        flows={'B','C37'};
    end
    E=stage7a5_generate_split(catalog,groups.inlib,base,cfg, ...
        cfg.seed_E,cfg.n_E_per_class,'E',false);
    sigma=estimate_sigma(E);
    A=stage7a5_generate_split(catalog,groups.inlib,base,cfg, ...
        cfg.seed_A,cfg.n_A_per_class,'A',false);
    F=stage7a5_generate_split(catalog,groups.inlib,base,cfg, ...
        cfg.seed_F,cfg.n_F_per_class,'F',false);
    testcfg=cfg;testcfg.true_main_bounds=cfg.test_main_bounds;
    tests=[ ...
        stage7a5_generate_split(catalog,groups.inlib,base,testcfg, ...
            cfg.seed_T_inlib,cfg.n_T_inlib_per_topology,'T_inlib',false); ...
        stage7a5_generate_split(catalog,groups.old_out,base,testcfg, ...
            cfg.seed_T_old_out,cfg.n_T_old_out_per_topology,'T_old_out',false); ...
        stage7a5_generate_split(catalog,groups.reachable,base,testcfg, ...
            cfg.seed_T_reachable,cfg.n_T_reachable_per_topology,'T_reachable',false); ...
        stage7a5_generate_split(catalog,groups.grammar_out,base,testcfg, ...
            cfg.seed_T_grammar_out,cfg.n_T_grammar_out_per_topology, ...
            'T_grammar_out',false); ...
        stage7a5_generate_split(catalog,groups.domain,base,testcfg, ...
            cfg.seed_T_domain,cfg.n_T_domain_per_topology,'T_domain',true)];
    assert_unique_scenarios(E,A,F,tests);
    sample_rows=repmat(sample_row(),0,1);
    candidate_rows=repmat(candidate_row(),0,1);
    calibration_rows=repmat(calibration_row(),0,1);
    for v=1:numel(cfg.observation_schemes)
        views=cfg.observation_views{v};scheme=cfg.observation_schemes{v};
        for f=1:numel(flows)
            flow=flows{f};
            [chosenpool,chosenbank,chosencfg,budget,kind]= ...
                choose_flow(flow,pool,newbank,oldpool,oldbank,cfg);
            scoredA=score_batch(A,flow,chosenpool,chosenbank,base, ...
                chosencfg,base_ix,views,sigma,[],budget);
            scoredF=score_batch(F,flow,chosenpool,chosenbank,base, ...
                chosencfg,base_ix,views,sigma,[],budget);
            delta=nonconformity(scoredA,A);
            fit=cellfun(@(x)x.fit_statistic,scoredF);
            if strcmp(kind,'B'),cal_indices=base_ix;
            else,cal_indices=1:numel(chosenpool);end
            model=stage7a5_calibrate_split(delta,fit,chosenbank,chosencfg, ...
                cal_indices,views,sigma,kind,budget);
            model.condition_identity=stage7a7_condition_identity( ...
                chosencfg,chosenbank,views,sigma,flow,budget);
            calibration_rows(end+1)=make_calibration_row(cfg,scheme,flow, ...
                budget,model,numel(A),numel(F),sigma); %#ok<AGROW>
            for i=1:numel(tests)
                [r,c]=evaluate_one(tests(i),scheme,flow,budget,model, ...
                    chosenpool,chosenbank,base,chosencfg,base_ix, ...
                    views,sigma,steps);
                sample_rows(end+1)=r; %#ok<AGROW>
                candidate_rows=[candidate_rows;c(:)]; %#ok<AGROW>
            end
            fprintf('Stage 7A.7 %s %s %s %s: %d test observations\n', ...
                mode,condition,scheme,flow,numel(tests));
        end
    end
    summary=aggregate(sample_rows,false);
    topology_summary=aggregate(sample_rows,true);
    inventory=topology_inventory(catalog,pool,base_ix,steps);
    seeds=seed_manifest(cfg);
    noiseless=noiseless_controls(pool,base,cfg);
    writetable(struct2table(sample_rows),fullfile(cfg.output_dir,'samples.csv'));
    writetable(struct2table(candidate_rows), ...
        fullfile(cfg.output_dir,'candidate_audit.csv'));
    writetable(struct2table(summary),fullfile(cfg.output_dir,'summary.csv'));
    writetable(struct2table(topology_summary), ...
        fullfile(cfg.output_dir,'topology_summary.csv'));
    writetable(struct2table(calibration_rows), ...
        fullfile(cfg.output_dir,'calibration.csv'));
    writetable(struct2table(inventory), ...
        fullfile(cfg.output_dir,'topology_inventory.csv'));
    writetable(struct2table(seeds), ...
        fullfile(cfg.output_dir,'seed_manifest.csv'));
    writetable(struct2table(noiseless), ...
        fullfile(cfg.output_dir,'noiseless_controls.csv'));
    protocol_identity=stage4a4_scientific_config_hash(struct( ...
        'version',cfg.version,'condition',condition, ...
        'frequency_hz',cfg.frequency_hz, ...
        'train',cfg.frequency_train_indices, ...
        'holdout',cfg.frequency_holdout_indices, ...
        'noise_zin',cfg.zin_error_rms_ohm, ...
        'test_main_bounds',cfg.test_main_bounds, ...
        'pool_signatures',{newbank.candidate_signatures}, ...
        'seeds',seeds));
    runtime_s=toc(started);peak_rss_kb=process_peak_rss_kb();
    meta=table(string(cfg.verification_baseline_commit),true, ...
        string(version),string(computer('arch')),string(mode), ...
        string(condition),string(protocol_identity), ...
        string(newbank.identity),numel(pool),numel(tests), ...
        newbank.forward_calls,newbank.build_time_s, ...
        newbank.logical_cache_bytes,legacy_calls(oldbank), ...
        legacy_time(oldbank),peak_rss_kb,runtime_s, ...
        cfg.use_parallel,cfg.worker_count, ...
        string(datetime('now','TimeZone','UTC', ...
        'Format','yyyy-MM-dd HH:mm:ss')), ...
        'VariableNames',{'baseline_commit','git_dirty_during_run', ...
        'matlab_version','computer_arch','mode','condition', ...
        'protocol_identity','new_bank_identity','pool_size', ...
        'test_observations','new_template_forward_calls', ...
        'new_template_build_time_s','new_template_cache_bytes', ...
        'old_template_forward_calls','old_template_build_time_s', ...
        'process_peak_rss_kb','runtime_s','use_parallel', ...
        'worker_count','verification_time_utc'});
    writetable(meta,fullfile(cfg.output_dir,'metadata.csv'));
    save(fullfile(cfg.output_dir,'config_snapshot.mat'), ...
        'cfg','grammar','groups','sigma','meta','-v7');
    fprintf('Stage 7A.7 %s %s complete: %d decisions, %.2f s, %.0f kB peak RSS\n', ...
        mode,condition,numel(sample_rows),runtime_s,peak_rss_kb);
    out=struct('output_dir',cfg.output_dir,'runtime_s',runtime_s, ...
        'peak_rss_kb',peak_rss_kb,'summary',summary, ...
        'protocol_identity',protocol_identity);
end

function [chosenpool,bank,chosencfg,budget,kind]= ...
        choose_flow(flow,pool,newbank,oldpool,oldbank,cfg)
    chosencfg=cfg;
    if strcmp(flow,'B')
        chosenpool=pool;bank=newbank;budget=0;kind='B';
    elseif strcmp(flow,'C17')
        assert(~isempty(oldbank),'stage7a7:MissingLegacyBank');
        chosenpool=oldpool;bank=oldbank;budget=17;kind='C';
        chosencfg.candidate_budgets=[3 5 7 10 17];
        chosencfg.max_forward_template_evaluations=17* ...
            numel(cfg.main_scale_grid)*numel(cfg.load_scale_grid);
    else
        chosenpool=pool;bank=newbank;kind='C';
        budget=str2double(flow(2:end));
        assert(ismember(budget,cfg.candidate_budgets),'stage7a7:Flow');
    end
end
function scored=score_batch(samples,flow,pool,bank,base,cfg,base_ix, ...
        views,sigma,model,budget)
    scored=cell(numel(samples),1);
    for i=1:numel(samples)
        scored{i}=score_one(samples(i).observed,flow,pool,bank,base,cfg, ...
            base_ix,views,sigma,model,budget);
    end
end
function out=score_one(observed,flow,pool,bank,base,cfg,base_ix, ...
        views,sigma,model,budget)
    if ~isempty(model)
        expected=stage7a7_condition_identity(cfg,bank,views,sigma,flow,budget);
        assert(isfield(model,'condition_identity')&& ...
            strcmp(model.condition_identity,expected)&& ...
            isequal(model.sigma,sigma),'stage7a7:ConditionIdentityMismatch');
    end
    if strcmp(flow,'B')
        out=stage7a5_score_observation(observed,pool,bank,base,cfg, ...
            base_ix,views,sigma,'B',0,model);
        out.profile_evaluations=numel(base_ix);
    elseif strcmp(flow,'C17')
        out=stage7a6_score_observation(observed,pool,bank,base,cfg, ...
            base_ix,views,sigma,budget,model);
    else
        out=stage7a7_score_observation(observed,pool,bank,base,cfg, ...
            base_ix,views,sigma,budget,model);
    end
    if ~isfield(out,'completion_ids'),out.completion_ids={};end
    if ~isfield(out,'pool_exhausted')
        out.pool_exhausted=numel(out.candidate_ids)==numel(pool);
    end
    if ~isfield(out,'unvisited_count')
        out.unvisited_count=numel(pool)-numel(out.candidate_ids);
    end
    if ~isfield(out,'budget_blocked_count'),out.budget_blocked_count=NaN;end
    if ~isfield(out,'frontier_limited'),out.frontier_limited=false;end
end
function delta=nonconformity(scored,samples)
    delta=zeros(numel(samples),1);
    for i=1:numel(samples)
        j=find(strcmp(scored{i}.candidate_ids,samples(i).truth_id),1);
        assert(~isempty(j),'stage7a7:CalibrationMissedTruth');
        delta(i)=scored{i}.distances(j)-min(scored{i}.distances);
    end
end
function sigma=estimate_sigma(samples)
    squared=zeros(1,2);
    for i=1:numel(samples)
        for v=1:2
            squared(v)=squared(v)+mean(abs(samples(i).observed{v}- ...
                samples(i).clean{v}).^2);
        end
    end
    sigma=sqrt(squared/numel(samples));
end
function assert_unique_scenarios(E,A,F,T)
    all=[E;A;F;T];parameter=[all.parameter_seed];noise=[all.noise_seed];
    assert(numel(unique(parameter))==numel(parameter)&& ...
        numel(unique(noise))==numel(noise)&& ...
        isempty(intersect(parameter,noise)), ...
        'stage7a7:SeedOverlap','Simulation parameter/noise seeds overlap.');
end
function [r,candidates]=evaluate_one(s,scheme,flow,budget,model, ...
        pool,bank,base,cfg,base_ix,views,sigma,steps)
    t=tic;
    scored=score_one(s.observed,flow,pool,bank,base,cfg, ...
        base_ix,views,sigma,model,budget);
    decision=stage7a5_decide(scored,model,bank);
    elapsed=toc(t);
    [~,order]=sortrows([scored.distances(:),(1:numel(scored.distances)).'],[1 2]);
    best=scored.candidate_ids{order(1)};second='';second_d=NaN;
    if numel(order)>1
        second=scored.candidate_ids{order(2)};
        second_d=scored.distances(order(2));
    end
    ix=find(strcmp(scored.candidate_ids,s.truth_id),1);
    truth_d=NaN;truth_rank=0;
    if ~isempty(ix)
        truth_d=scored.distances(ix);truth_rank=find(order==ix,1);
    end
    competitor='';competitor_d=NaN;
    jj=find(~strcmp(scored.candidate_ids(order),s.truth_id),1);
    if ~isempty(jj)
        competitor=scored.candidate_ids{order(jj)};
        competitor_d=scored.distances(order(jj));
    end
    sample_id=sprintf('%s_%s_%03d',s.split,s.truth_id,s.replicate);
    unique=strcmp(decision.decision_state,'UNIQUE_CONFIDENT');
    generated=any(strcmp(scored.generated_ids,s.truth_id));
    completion=any(strcmp(scored.completion_ids,s.truth_id));
    r=sample_row();r.sample_id=sample_id;r.split=s.split;
    r.scenario=scenario_name(s);r.condition=cfg.condition;
    r.scheme=scheme;r.flow=flow;r.budget=budget;
    r.truth_id=s.truth_id;r.truth_signature=s.truth_signature;
    r.truth_in_initial=any(strcmp(bank.candidate_ids(base_ix),s.truth_id));
    r.truth_in_search_pool=any(strcmp(bank.candidate_ids,s.truth_id));
    r.theoretically_reachable=isfinite(steps(s.truth_index));
    r.min_edit_steps=steps(s.truth_index);r.domain_out=s.domain_out;
    r.parameter_seed=s.parameter_seed;r.noise_seed=s.noise_seed;
    r.true_main_scale=s.theta_true.main_length_scale;
    r.true_load_scale=s.theta_true.branch_load_scale;
    r.generated_by_edit=generated;r.added_by_completion=completion;
    r.active=~isempty(ix);r.truth_in_set= ...
        any(strcmp(decision.candidate_set,s.truth_id));
    r.candidate_count=numel(scored.candidate_ids);
    r.profile_evaluations=scored.profile_evaluations;
    r.optimizer_evaluations=scored.optimizer_evaluations;
    r.holdout_forward_calls=scored.forward_model_calls_holdout;
    r.forward_calls=scored.optimizer_evaluations+ ...
        scored.forward_model_calls_holdout;
    r.wall_clock_s=elapsed;r.pool_exhausted=scored.pool_exhausted;
    r.search_truncated=scored.search_truncated;
    r.unvisited_count=scored.unvisited_count;
    r.budget_blocked_count=scored.budget_blocked_count;
    r.frontier_limited=scored.frontier_limited;
    r.best_candidate=best;r.second_candidate=second;
    r.truth_rank=truth_rank;r.truth_distance=truth_d;
    r.closest_competitor=competitor;r.competitor_distance=competitor_d;
    r.distance_1=decision.distance_1;r.distance_2=second_d;
    r.margin=decision.margin;r.candidate_set= ...
        strjoin(decision.candidate_set,';');
    r.set_size=decision.candidate_set_size;
    r.fit_statistic=decision.fit_statistic;
    r.fit_threshold=decision.fit_threshold;
    r.fit_pass=decision.fit_pass;
    r.state=decision.decision_state;r.reason=decision.decision_reason;
    r.correct_unique=unique&&strcmp(best,s.truth_id);
    r.false_unique=unique&&~strcmp(best,s.truth_id);
    candidates=repmat(candidate_row(),numel(scored.candidate_ids),1);
    for j=1:numel(scored.candidate_ids)
        c=candidate_row();ci=scored.candidate_indices(j);
        c.sample_id=sample_id;c.split=s.split;c.scenario=r.scenario;
        c.condition=cfg.condition;c.scheme=scheme;c.flow=flow;
        c.budget=budget;c.truth_id=s.truth_id;
        c.candidate_id=scored.candidate_ids{j};
        c.signature=bank.candidate_signatures{ci};
        c.rank=find(order==j,1);c.distance=scored.distances(j);
        c.fit_main_scale=scored.params(j,1);
        c.fit_load_scale=scored.params(j,2);
        c.generated_by_edit=any(strcmp(scored.generated_ids,c.candidate_id));
        c.added_by_completion=any(strcmp(scored.completion_ids,c.candidate_id));
        c.truth_candidate=strcmp(c.candidate_id,s.truth_id);
        c.in_candidate_set=any(strcmp(decision.candidate_set,c.candidate_id));
        candidates(j)=c;
    end
end
function name=scenario_name(s)
    name=s.truth_id;
    if strcmp(name,'J30_000'),name='MID30';end
    if strcmp(name,'J50_000'),name='MID50';end
    if s.domain_out,name=[name '_domain_out'];end
end
