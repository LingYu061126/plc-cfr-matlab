function rows=noiseless_controls(pool,base,cfg)
    ids={pool.topology_id};
    pairs={{'G003','MIRROR_M3'},{'J30_000','J50_000'}, ...
        {'J30_000','G002'},{'J50_000','G002'}};
    theta=struct('main_length_scale',1,'branch_length_scale',1, ...
        'branch_load_scale',1,'first_segment_scale',1, ...
        'source_impedance_ohm',50,'receiver_impedance_ohm',50);
    rows=repmat(struct('first_id','','second_id','', ...
        'h_complex_rms',NaN,'zin_complex_rms_ohm',NaN, ...
        'h_max_abs',NaN,'zin_max_abs_ohm',NaN, ...
        'frequency_count',0,'frequency_first_hz',NaN, ...
        'frequency_last_hz',NaN,'main_scale',1,'load_scale',1), ...
        numel(pairs),1);
    for k=1:numel(pairs)
        a=find(strcmp(ids,pairs{k}{1}),1);
        b=find(strcmp(ids,pairs{k}{2}),1);
        x=stage7a4_forward_state(pool(a).network,theta,base, ...
            cfg.frequency_hz,cfg.state_50);
        y=stage7a4_forward_state(pool(b).network,theta,base, ...
            cfg.frequency_hz,cfg.state_50);
        dh=x.H_endpoint-y.H_endpoint;dz=x.Zin-y.Zin;
        rows(k)=struct('first_id',ids{a},'second_id',ids{b}, ...
            'h_complex_rms',sqrt(mean(abs(dh).^2)), ...
            'zin_complex_rms_ohm',sqrt(mean(abs(dz).^2)), ...
            'h_max_abs',max(abs(dh)), ...
            'zin_max_abs_ohm',max(abs(dz)), ...
            'frequency_count',numel(cfg.frequency_hz), ...
            'frequency_first_hz',cfg.frequency_hz(1), ...
            'frequency_last_hz',cfg.frequency_hz(end), ...
            'main_scale',1,'load_scale',1);
    end
end
