function rows=topology_inventory(catalog,pool,base_ix,steps)
    rows=repmat(struct('topology_id','','signature','', ...
        'in_initial_library',false,'in_new_pool',false, ...
        'main_segments',0,'branch_count',0, ...
        'main_length_total_m',NaN,'min_edit_steps',NaN), ...
        numel(catalog),1);
    for k=1:numel(catalog)
        net=catalog(k).network;
        rows(k)=struct('topology_id',catalog(k).topology_id, ...
            'signature',stage6b_network_signature(net), ...
            'in_initial_library',ismember(k,base_ix), ...
            'in_new_pool',k<=numel(pool), ...
            'main_segments',numel(net.main_lengths), ...
