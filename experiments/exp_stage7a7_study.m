function rows=aggregate(samples,by_topology)
    rows=repmat(summary_row(),0,1);
    splits=unique({samples.split},'stable');
    schemes=unique({samples.scheme},'stable');
    flows=unique({samples.flow},'stable');
    for a=1:numel(splits)
        for b=1:numel(schemes)
            for c=1:numel(flows)
                primary=strcmp({samples.split},splits{a})& ...
                    strcmp({samples.scheme},schemes{b})& ...
                    strcmp({samples.flow},flows{c});
                if ~any(primary),continue;end
                if by_topology
                    scenarios=unique({samples(primary).scenario},'stable');
                else
                    scenarios={''};
                end
                for d=1:numel(scenarios)
                    ix=primary;
                    if by_topology
                        ix=ix&strcmp({samples.scenario},scenarios{d});
                    end
                    x=samples(ix);n=numel(x);
                    q=summary_row();q.condition=x(1).condition;
                    q.split=splits{a};q.scenario=scenarios{d};
                    q.scheme=schemes{b};q.flow=flows{c};
                    q.budget=x(1).budget;q.n=n;
                    q.correct_unique_k=sum([x.correct_unique]);
                    q.false_unique_k=sum([x.false_unique]);
                    q.rejected_k=sum(strcmp({x.state},'REJECTED'));
                    q.ambiguous_k=sum(strcmp({x.state},'MULTIPLE_AMBIGUOUS'));
                    q.low_confidence_k=sum(strcmp({x.state},'LOW_CONFIDENCE'));
                    q.generated_by_edit_k=sum([x.generated_by_edit]);
                    q.added_by_completion_k=sum([x.added_by_completion]);
                    q.active_k=sum([x.active]);
                    q.truth_in_set_k=sum([x.truth_in_set]);
                    q.nonempty_set_k=sum([x.set_size]>0);
                    q.truncated_k=sum([x.search_truncated]);
                    q.pool_exhausted_k=sum([x.pool_exhausted]);
                    q.mean_set_size=mean([x.set_size]);
                    q.mean_scored_candidates=mean([x.candidate_count]);
                    q.mean_unvisited=mean([x.unvisited_count]);
                    q.mean_profile_evaluations=mean([x.profile_evaluations]);
                    q.mean_optimizer_evaluations=mean([x.optimizer_evaluations]);
                    q.mean_forward_calls=mean([x.forward_calls]);
                    q.mean_wall_clock_s=mean([x.wall_clock_s]);
                    [q.correct_unique_low,q.correct_unique_high]= ...
                        stage7a4_wilson(q.correct_unique_k,n);
                    [q.false_unique_low,q.false_unique_high]= ...
                        stage7a4_wilson(q.false_unique_k,n);
                    [q.generated_low,q.generated_high]= ...
                        stage7a4_wilson(q.generated_by_edit_k,n);
                    rows(end+1)=q; %#ok<AGROW>
                end
            end
        end
    end
end
